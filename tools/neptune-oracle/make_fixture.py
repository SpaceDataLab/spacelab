"""Turn a NEPTUNE .mcs run into a committed fixture the Rust test can read without NEPTUNE.

The oracle is built and run here; CI only ever sees the numbers it produced. That is the same shape
the HWM14 harness uses, and it is what keeps the comparison honest about *when* it was measured: the
fixture carries the deck's force settings in its header, so a later reader can tell what was and was
not turned on rather than inferring it from the residual.

The start epoch is written as raw ET seconds, computed here by SPICE. Passing a calendar string to
the Rust side instead would put a UTC-to-TDB conversion inside the comparison, which is a second
implementation difference nobody asked to measure.
"""

import argparse
import sys

import spiceypy as spice
from check_lro import read_mcs, utc_to_et


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mcs", required=True)
    parser.add_argument("--lsk", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--stride-seconds", type=float, default=3600.0)
    parser.add_argument(
        "--settings", required=True, help="one line naming the deck's forces"
    )
    args = parser.parse_args()

    spice.furnsh(args.lsk)
    epochs, states = read_mcs(args.mcs)
    start = utc_to_et(epochs[0])

    rows = []
    for stamp, state in zip(epochs, states, strict=True):
        elapsed = utc_to_et(stamp) - start
        if rows and elapsed - rows[-1][0] < args.stride_seconds - 1e-6:
            continue
        rows.append((elapsed, *state))

    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(
            "# NEPTUNE selenocentric reference arc, MCRF (GCRF-aligned, Moon-centred).\n"
        )
        handle.write(
            "# GENERATED by tools/neptune-oracle/make_fixture.py -- do not edit by hand.\n"
        )
        handle.write(f"# forces: {args.settings}\n")
        handle.write(f"# start_utc {epochs[0]}\n")
        handle.write(f"# start_et_seconds {start!r}\n")
        handle.write("# columns: elapsed_s x_km y_km z_km vx_kms vy_kms vz_kms\n")
        for row in rows:
            handle.write(
                f"{row[0]:.6f} " + " ".join(f"{value:.9f}" for value in row[1:]) + "\n"
            )
    print(f"{len(rows)} rows -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
