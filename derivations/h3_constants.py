"""Transcribe the constants that fix the H3 grid into Maxima (plans/17 Ф17.P).

H3's specification is in practice Uber's C library; the grid it defines is fixed by a handful of
numbers in it: the 20 icosahedron face centres and the azimuths of each face's ijk axes
(`faceijk.c`), the gnomonic unit length of resolution 0, the Class III rotation and sqrt(7)
(`constants.h`, `faceijk.c`). Release v4.5.0, Apache-2.0, `tools/fetch-specs.sh` entries
`h3-faceijk` and `h3-constants`. Each decimal literal becomes the exact rational its text denotes, so
`h3_definition.mac` works with the numbers as written and nothing rounds them on the way in.

    python3 -I h3_constants.py <faceijk.c> <constants.h> <h3_constants.mac>
"""

from __future__ import annotations

import pathlib
import re
import sys
from decimal import Decimal
from fractions import Fraction

NUMBER = re.compile(r"-?\d+\.\d+(?:[eE][-+]?\d+)?")


def rational(text: str) -> str:
    f = Fraction(Decimal(text))
    return str(f.numerator) if f.denominator == 1 else f"{f.numerator}/{f.denominator}"


def block(source: str, name: str) -> list[str]:
    start = source.index(name)
    body = source[source.index("{", start) : source.index("};", start)]
    body = re.sub(r"//[^\n]*", "", body)
    return NUMBER.findall(body)


def define(source: str, name: str) -> str:
    m = re.search(rf"#define {name} ({NUMBER.pattern})", source)
    if m is None:
        raise SystemExit(f"{name} not found")
    return m.group(1)


def rows(values: list[str], width: int) -> str:
    out = [values[i : i + width] for i in range(0, len(values), width)]
    return ",\n  ".join("[" + ", ".join(rational(v) for v in r) + "]" for r in out)


def main() -> None:
    faceijk = pathlib.Path(sys.argv[1]).read_text()
    constants = pathlib.Path(sys.argv[2]).read_text()
    centres = block(faceijk, "faceCenterPoint[NUM_ICOSA_FACES]")
    axes = block(faceijk, "faceAxesAzRadsCII[NUM_ICOSA_FACES][3]")
    if len(centres) != 60 or len(axes) != 60:
        raise SystemExit(
            f"expected 60 and 60 numbers, read {len(centres)} and {len(axes)}"
        )
    text = (
        "/* Generated by derivations/h3_constants.py from Uber H3 v4.5.0 `faceijk.c` and\n"
        "   `constants.h` (Apache-2.0). Do not edit: verify.sh regenerates it from the pinned files. */\n\n"
        f"h3_face_centre : [\n  {rows(centres, 3)}]$\n\n"
        f"h3_face_axes_az : [\n  {rows(axes, 3)}]$\n\n"
        f"h3_ap7_rot : {rational(define(constants, 'M_AP7_ROT_RADS'))}$\n"
        f"h3_res0_u_gnomonic : {rational(define(constants, 'RES0_U_GNOMONIC'))}$\n"
        f"h3_inv_res0_u_gnomonic : {rational(define(constants, 'INV_RES0_U_GNOMONIC'))}$\n"
        f"h3_sqrt7 : {rational(define(faceijk, 'M_SQRT7'))}$\n"
    )
    pathlib.Path(sys.argv[3]).write_text(text)


if __name__ == "__main__":
    main()
