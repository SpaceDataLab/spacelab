"""Subsample NEPTUNE's geocentric `.csv` output into the committed comparison fixture.

The `.csv` is GCRF and one row per minute; the test needs neither that density nor the header, so
this keeps every `--stride-minutes`-th row and carries the epoch across as a UTC stamp. Elapsed time
is the difference of the UTC stamps, which is the same number as elapsed TT over an arc with no leap
second in it -- and there is none in 2019-06-25.

Run: python3 tools/neptune-oracle/make_sentinel1b_fixture.py [RUN_DIR] [--stride-minutes N]
"""

import datetime as dt
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
DEST = ROOT / "crates/spacelab/tests/fixtures/neptune_sentinel1b_xgm.txt"


def read_csv(path: pathlib.Path) -> list[tuple[dt.datetime, list[float]]]:
    rows = []
    for line in path.read_text().splitlines():
        if line.startswith("#") or not line.strip():
            continue
        field = line.split()
        stamp = dt.datetime.strptime(field[0], "%Y-%m-%dT%H:%M:%S.%f%z")
        rows.append((stamp, [float(x) for x in field[2:8]]))
    return rows


def main() -> int:
    arguments = [a for a in sys.argv[1:] if not a.startswith("--")]
    run = (
        pathlib.Path(arguments[0])
        if arguments
        else ROOT / "data/oracles/neptune-s1b-xgm"
    )
    stride = next(
        (
            int(a.removeprefix("--stride-minutes="))
            for a in sys.argv[1:]
            if a.startswith("--stride-minutes=")
        ),
        10,
    )
    rows = read_csv(run / "output/neptune.csv")
    start = rows[0][0]
    lines = [
        "# NEPTUNE geocentric reference arc, GCRF.",
        "# GENERATED by tools/neptune-oracle/make_sentinel1b_fixture.py -- do not edit by hand.",
        "# forces: XGM2019e degree 70 (pushed into NEPTUNE by make_gravity_overlay.py) + Sun and Moon",
        "# point masses (DE-421); drag, SRP, albedo and both tide models off.",
        "# initial state: Sentinel-1B POE OSV at 2019-06-25T00:00:02Z, ITRF, converted by NEPTUNE.",
        f"# start_utc {start.isoformat().replace('+00:00', 'Z')}",
        "# columns: elapsed_s x_km y_km z_km vx_kms vy_kms vz_kms",
    ]
    for index in range(0, len(rows), stride):
        stamp, state = rows[index]
        elapsed = (stamp - start).total_seconds()
        lines.append(f"{elapsed:.6f} " + " ".join(f"{value:.9f}" for value in state))
    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text("\n".join(lines) + "\n")
    print(f"wrote {DEST}  ({len(lines) - 7} rows, stride {stride} min)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
