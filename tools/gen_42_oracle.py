"""Generate the NASA 42 fixture for the control pillar's second oracle.

42 (`ericstoneking/42`, NASA Goddard) is released under the **NASA Open Source Agreement v1.3**,
confirmed from `License/NASA Open Source Software Agreement.pdf` in the distribution -- GitHub
reports no SPDX identifier for it, so the licence has to be read rather than looked up. NOSA is
reciprocal-flavoured: §3.A requires any redistribution to be under NOSA, §3.B a prominent notice,
§3.C a changelog identifying Modifications, §3.F requests registration of Modifications, §3.I
carves out Larger Works and §3.J adds an export notice.

None of that binds here, and the reason is worth stating rather than assuming: **42 is run
unmodified, from input decks only, and neither it nor any part of it is redistributed.** Everything
this script needs -- passive flight software, gravity-gradient torque on and every other environment
torque off, the inertia tensor, the initial attitude and rate, the orbit -- is reachable from
`Inp_Sim.txt`, `Orb_LEO.txt` and `SC_Simple.txt`. No source file is touched, so no Modification
exists to changelog or register. The fixture holds numbers 42 printed, cited to it, which is the
same footing as every other oracle in this workspace.

42 is therefore an oracle and never a dependency. It is not vendored, not built by CI, and not in
any manifest; the fixture is committed and the run that produced it is reproducible from here.

# What this measures that Basilisk does not

Basilisk and this workspace agree on the closed loop to 1.2e-11 rad (see `basilisk_oracle.rs`), and
two implementations agreeing is worth less than three. 42 is an independent code base with an
independent rigid-body formulation, and the leg it supplies is the one Basilisk's fixture covers
only pointwise: **gravity-gradient torque driving the attitude over a whole orbit arc**, rather than
the torque evaluated at five sampled geometries.

The scenario is deliberately hostile to a convention error. The body tumbles at ~0.7 deg/s, so the
gravity-gradient torque sweeps through the body frame instead of sitting on one axis, and the
inertia is fully asymmetric (10, 12, 8 kg m^2) so every product in `r x (I r)` contributes.

Run:  timeout 600 uv run python tools/gen_42_oracle.py
with `SPACELAB_42_ROOT` pointing at a built 42, or the default cache location below.
"""

from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent
FIXTURES = REPO / "crates" / "spacelab-control" / "tests" / "fixtures"
ROOT = Path(
    os.environ.get("SPACELAB_42_ROOT", Path.home() / ".cache/spacelab/oracles/42")
)

# 42's own Earth gravitational parameter, from the `Mu[10]` world table in `Source/42init.c`. It is
# 3 e6 m^3/s^2 above Basilisk's 3.986004415e14 -- 7.5e-9 relative, which is above the level this
# comparison resolves, so the constant is taken from the oracle being compared against rather than
# shared between them.
MU_42 = 3.986004418e14

MOMENTS = (10.0, 12.0, 8.0)
MASS = 100.0
RADIUS = 6.778137e6
INCLINATION = np.deg2rad(52.0)
# ~0.7 deg/s about a general axis: fast enough that the torque sweeps the body frame within the arc,
# slow enough that a 0.5 s step is nowhere near the stability limit of anybody's integrator.
OMEGA0 = (0.3, 0.4, 0.5)  # deg/s, expressed in the body frame
# A general attitude, so no axis of the inertia tensor starts aligned with anything.
AXIS0 = np.array([1.0, 2.0, 3.0])
ANGLE0 = np.deg2rad(40.0)

SPAN = 2000.0
STEPS = (0.5, 0.25, 0.125, 0.0625)
SAMPLE = 100.0

HEADER = """# NASA 42 (ericstoneking/42, NASA Goddard Space Flight Center), NASA Open Source
# Agreement v1.3. Run unmodified from input decks; no source touched, nothing redistributed.
# Generated by tools/gen_42_oracle.py -- do not edit.
"""


def quaternion() -> np.ndarray:
    """The initial attitude as 42 wants it: vector part first, scalar last."""
    axis = AXIS0 / np.linalg.norm(AXIS0)
    return np.concatenate([axis * np.sin(0.5 * ANGLE0), [np.cos(0.5 * ANGLE0)]])


def initial_state() -> tuple[np.ndarray, np.ndarray]:
    """A circular orbit in 42's own `mu`, so the arc has a closed form to check the fixture against.

    Circular rather than merely low-eccentricity because the test propagates `r(t)` analytically
    instead of running a second orbit solver: `R(cos nt) u + R(sin nt) v` is exact, and the residual
    against 42's own `PosN` then measures 42's orbit rather than hiding inside a solver difference.
    """
    speed = np.sqrt(MU_42 / RADIUS)
    r = np.array([RADIUS, 0.0, 0.0])
    v = speed * np.array([0.0, np.cos(INCLINATION), np.sin(INCLINATION)])
    return r, v


def vec(v) -> str:
    return " ".join(f"{x:+.15e}" for x in np.asarray(v).ravel())


def edit(path: Path, replacements: list[tuple[str, str]]) -> None:
    text = path.read_text()
    for old, new in replacements:
        if old not in text:
            raise SystemExit(
                f"{path.name}: deck line not found, 42 version drift?\n  {old!r}"
            )
        text = text.replace(old, new, 1)
    path.write_text(text)


def run(step: float) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """One 42 run at one step size, returning `(t, PosN, qbn, wbn)` at the sample times."""
    if not (ROOT / "42").is_file():
        raise SystemExit(
            f"no 42 executable at {ROOT / '42'}; set SPACELAB_42_ROOT to a built 42 tree"
        )
    work = ROOT.parent / "42-runs" / f"gg-{step}"
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    shutil.copytree(ROOT / "InOut", work, dirs_exist_ok=True)

    edit(
        work / "Inp_Sim.txt",
        [
            (
                "10000.0     0.1                 !  Sim Duration, Step Size [sec]",
                f"{SPAN:.6f} {step:.10f}    !  Sim Duration, Step Size [sec]",
            ),
            (
                "10.0                            !  File Output Interval [sec]",
                f"{SAMPLE:.6f}                     !  File Output Interval [sec]",
            ),
            (
                "TRUE                            !  Graphics Front End?",
                "FALSE                           !  Graphics Front End?",
            ),
            (
                "IGRF                            !  Magfield (NONE,DIPOLE,IGRF)",
                "NONE                            !  Magfield (NONE,DIPOLE,IGRF)",
            ),
            (
                "FALSE                           !  Gravity Gradient Torques",
                "TRUE                            !  Gravity Gradient Torques",
            ),
        ],
    )

    r, v = initial_state()
    edit(
        work / "Orb_LEO.txt",
        [
            (
                "KEP                           !  Use Keplerian elements (KEP) or (RV) or FILE",
                "RV                            !  Use Keplerian elements (KEP) or (RV) or FILE",
            ),
            (
                "6678.0  0.0  0.0              !  RV Initial Position (km)",
                f"{vec(r / 1e3)}  !  RV Initial Position (km)",
            ),
            (
                "0.0  8.5  0.0                 !  RV Initial Velocity (km/sec)",
                f"{vec(v / 1e3)}  !  RV Initial Velocity (km/sec)",
            ),
        ],
    )

    edit(
        work / "SC_Simple.txt",
        [
            (
                "INSTANT_FSW                 !  Flight Software Identifier",
                "PASSIVE_FSW                 !  Flight Software Identifier",
            ),
            # 42 refuses to start if the flight-software sample time is below the dynamics step,
            # so it tracks the step. `PASSIVE_FSW` computes no command, so the rate is inert.
            (
                "0.2                         !  FSW Sample Time, sec",
                f"{step:.10f}              !  FSW Sample Time, sec",
            ),
            (
                "NAN                         ! Ang Vel wrt [NL], Att [QA] wrt [NLEF]",
                "NQN                         ! Ang Vel wrt [NL], Att [QA] wrt [NLEF]",
            ),
            (
                "0.3    0.4    0.5           ! Ang Vel (deg/sec)",
                f"{vec(OMEGA0)} ! Ang Vel (deg/sec)",
            ),
            (
                "0.0    0.0    0.0    1.0    ! Quaternion",
                f"{vec(quaternion())} ! Quaternion",
            ),
            (
                "100.0                       ! Mass",
                f"{MASS:.15e}    ! Mass",
            ),
            (
                "100.0  200.0  300.0         ! Moments of Inertia (kg-m^2)",
                f"{vec(MOMENTS)} ! Moments of Inertia (kg-m^2)",
            ),
        ],
    )

    subprocess.run(
        [str(ROOT / "42"), f"{work}/"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        timeout=600,
    )

    time = np.loadtxt(work / "time.42")
    # `PosN.42` carries three triples per row; the first is the spacecraft's inertial position, and
    # it starts bit-equal to the RV written into the deck, which is how that was established.
    pos = np.loadtxt(work / "PosN.42")[:, :3]
    qbn = np.loadtxt(work / "qbn.42")
    wbn = np.loadtxt(work / "wbn.42")
    return time, pos, qbn, wbn


def main() -> None:
    FIXTURES.mkdir(parents=True, exist_ok=True)
    r0, v0 = initial_state()
    lines = [
        HEADER,
        f"# inertia diag {vec(MOMENTS)}  mass {MASS:.15e} kg  mu {MU_42:.15e} m^3/s^2\n",
        f"# r_N(0) {vec(r0)} m\n",
        f"# v_N(0) {vec(v0)} m/s\n",
        f"# q_BN(0) {vec(quaternion())} (vector part first, scalar last)\n",
        f"# omega_BN_B(0) {vec(np.deg2rad(OMEGA0))} rad/s\n",
        "#\n",
        "# PASSIVE_FSW: no control torque. Gravity-gradient torque on, every other environment\n",
        "# torque off, so the only moment is 3 mu / R^5 * R x (I R) and the residual against\n",
        "# spacelab is that expression plus the rigid-body integration and nothing else.\n",
        "#\n",
        "# step_s t_s r_N(3) q_BN(4) omega_BN_B(3)\n",
    ]
    for step in STEPS:
        time, pos, qbn, wbn = run(step)
        for t, p, q, w in zip(time, pos, qbn, wbn, strict=True):
            lines.append(f"{step:.6f} {t:10.2f} {vec(p)} {vec(q)} {vec(w)}\n")
        print(f"42 at step {step} s: {len(time)} samples")
    (FIXTURES / "nasa42_gravity_gradient.txt").write_text("".join(lines))
    print(f"wrote {FIXTURES / 'nasa42_gravity_gradient.txt'}")


if __name__ == "__main__":
    main()
