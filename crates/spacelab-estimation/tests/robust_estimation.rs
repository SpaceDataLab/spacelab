//! What robustness buys and what it costs, measured on a contaminated tracking arc.
//!
//! The claim under test is not "the robust filter is better" — that is trivially arrangeable by
//! choosing the contamination. It is the pair of numbers a practitioner actually needs before
//! switching a production filter over:
//!
//! 1. **What does robustness cost when the data is clean?** An M-estimator throws away information
//!    at the tails, and the tails of a Gaussian are where a chunk of the Fisher information lives.
//!    The ticket says not to assume this is negligible, so it is measured at 0 % contamination.
//! 2. **What does it save when the data is not?** Measured at 1 %, 5 % and 20 % of observations
//!    corrupted at a known magnitude.
//!
//! # The experiment
//!
//! A six-state constant-velocity target, position observed on all three axes once per step as three
//! independent scalar updates. The truth is generated by *exactly* the discrete model the filter
//! assumes — the same `Φ` and the same `Q` from [`state_noise_compensation`] — so the filter is
//! correctly specified by construction and every departure from consistency in the results below is
//! attributable to the outliers and to what each estimator does about them, and to nothing else.
//! That is the point of a controlled experiment; a truth with model error as well would confound the
//! two effects and neither number would mean anything.
//!
//! Contamination is a `±20σ` bias added to a randomly chosen fraction of the scalar observations —
//! a known magnitude, so the influence functions in `robust.rs` predict what should happen.
//!
//! **The four estimators see byte-identical data.** The random stream is consumed only by the truth,
//! the measurement noise and the outlier draw, never by the filter, so seeding per contamination
//! level rather than per estimator makes this a paired comparison: an RMS ratio between two rows of
//! the table below is a difference in estimator, not a difference in realisation.
//!
//! # Measured — 100 runs × 300 steps × 3 axes = 90 000 scalar updates per cell
//!
//! RMS position error in metres, NEES against six degrees of freedom (consistent ≈ 6), and the
//! longest unbroken run of rejections on any one axis:
//!
//! ```text
//!                     0 %                1 %                5 %               20 %
//!                 RMS  NEES  run     RMS  NEES  run     RMS  NEES  run     RMS  NEES  run
//!   plain        4.41   6.2    0    9.96  23.6    0   20.14  92.7    0   37.84 337.5    0
//!   gate 3σ      4.51   6.3    2  931.97  17.2  299 1644.27 118.6  293 1894.05 956.1  294
//!   inflate 3σ   4.42   6.2    0    6.09   7.1    0   14.45  15.6    0   74.47 221.8    0
//!   Huber        4.48   6.2    0    5.92   7.4    0   11.58  15.5    0   22.29  42.7    0
//!   Student-t    4.52   6.6    0    5.86   7.5    0   11.53  14.9    0   22.73  38.4    0
//! ```
//!
//! **The efficiency loss on clean data is 0.11 % for inflation, 1.39 % for Huber, 2.19 % for the gate
//! and 2.43 % for the Student-t**, in RMS. That is the price. It is small, and it is not zero: at 0 %
//! contamination the plain Kalman filter is the best estimator in the table, which is what optimality
//! means and is worth seeing stated rather than assumed away.
//!
//! Then read across. The plain filter's error grows 8.6× and its NEES 55× — it is not merely wrong,
//! it is *confidently* wrong, which is the failure that matters operationally. Huber and the
//! Student-t hold to within 5× of their own clean baselines and are within 2 % of each other
//! everywhere; either is a defensible default.
//!
//! # The gate does not fail gracefully — it fails totally
//!
//! 932 m at 1 % contamination, against 4.4 m for doing nothing. The mechanism is in
//! `robust.rs`'s module documentation; the numbers that pin it are here. Three of them are worth
//! carrying away, because each defeats a different way of monitoring a filter:
//!
//! * **The rejection rate does not show it.** 7.4 % at 5 % contamination against 5.3 % expected.
//! * **NEES does not show it — it shows the opposite.** 17.2 for the locked-out gate against 23.6 for
//!   the plain filter at the same contamination, so a consistency monitor ranks the broken filter as
//!   the healthier one. A state drifting linearly under a covariance growing quadratically stays
//!   superficially calibrated while the error runs away.
//! * **The longest rejection run shows it immediately**: 299 out of 300 steps. At 5 % contamination a
//!   run of 10 has probability `1e-13`.
//!
//! # Robustness buys nothing against outliers you cannot see
//!
//! [`marginal_outliers_are_not_worth_defending_against`] repeats the 20 % cell with `3.5σ` outliers
//! instead of `20σ`: plain 7.97 m, Huber 7.47 m, Student-t 7.74 m, inflation 8.00 m. A 6 % gain for
//! Huber and nothing for the rest. An outlier that a filter cannot distinguish from noise cannot be
//! down-weighted without down-weighting the noise along with it, and the down-weighting is what costs
//! the 1.4 %. Robustness is insurance against gross errors, not a general-purpose improvement.

// `rejected` and `longest_rejection_run` are exact counts turned into exact fractions; comparing them
// against the literal they were built from is the assertion, not an approximation of one.
#![allow(
    clippy::unwrap_used,
    clippy::needless_range_loop,
    clippy::cast_precision_loss,
    clippy::float_cmp
)]

use core::fmt::Write as _;
use spacelab_estimation::{
    RobustPolicy, RobustTally, SquareRootKalman, normalized_squared, process_noise_sqrt,
    robust_update, state_noise_compensation,
};

const STEP: f64 = 10.0;
const STEPS: usize = 300;
const RUNS: usize = 100;
/// Per-axis position measurement noise.
const OBSERVATION_SIGMA: f64 = 10.0;
/// Unmodelled acceleration, as the square root of a spectral density (m·s⁻³ᐟ²).
const ACCELERATION_DENSITY: f64 = 1e-4;
const POSITION_SIGMA_0: f64 = 100.0;
const VELOCITY_SIGMA_0: f64 = 1.0;
const CONTAMINATION: [f64; 4] = [0.0, 0.01, 0.05, 0.20];
/// A three-sigma gate, exactly: `|ν| > 3√f`. See `chi_square_gate` for the tail-probability reading.
const GATE: f64 = 9.0;
const TUNING: f64 = 1.345;
const DEGREES_OF_FREEDOM: f64 = 5.0;

/// `SplitMix64` with a Box–Muller transform: a deterministic Gaussian source with no dependency, so
/// the table in the module documentation reproduces bit for bit.
struct Gaussian {
    state: u64,
    spare: Option<f64>,
}

impl Gaussian {
    const fn seeded(seed: u64) -> Self {
        Self {
            state: seed,
            spare: None,
        }
    }

    fn uniform(&mut self) -> f64 {
        self.state = self.state.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.state;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^= z >> 31;
        ((z >> 11) as f64 + 0.5) * (1.0 / 9_007_199_254_740_992.0)
    }

    fn normal(&mut self) -> f64 {
        if let Some(spare) = self.spare.take() {
            return spare;
        }
        let (u1, u2) = (self.uniform(), self.uniform());
        let radius = libm::sqrt(-2.0 * libm::log(u1));
        let angle = core::f64::consts::TAU * u2;
        self.spare = Some(radius * libm::sin(angle));
        radius * libm::cos(angle)
    }
}

/// The estimators under comparison. `noise_scale` multiplies the nominal `R` before it reaches the
/// policy: for the Student-t it converts a variance into the *scale* of a `t(ν)` with that variance,
/// `s = R(ν−2)/ν`, without which the comparison would be between two different noise levels rather
/// than between two estimators.
struct Estimator {
    name: &'static str,
    policy: RobustPolicy,
    noise_scale: f64,
}

fn estimators() -> [Estimator; 5] {
    [
        Estimator {
            name: "plain",
            policy: RobustPolicy::Plain,
            noise_scale: 1.0,
        },
        Estimator {
            name: "gate 3σ",
            policy: RobustPolicy::ChiSquareGate { threshold: GATE },
            noise_scale: 1.0,
        },
        Estimator {
            name: "inflate 3σ",
            policy: RobustPolicy::ChiSquareInflation { threshold: GATE },
            noise_scale: 1.0,
        },
        Estimator {
            name: "Huber",
            policy: RobustPolicy::Huber { tuning: TUNING },
            noise_scale: 1.0,
        },
        Estimator {
            name: "Student-t",
            policy: RobustPolicy::StudentT {
                degrees_of_freedom: DEGREES_OF_FREEDOM,
            },
            noise_scale: 1.0,
        },
    ]
}

struct Report {
    rms: f64,
    nees: f64,
    rejected: f64,
    mean_weight: f64,
    longest_rejection_run: u32,
}

/// Constant-velocity state transition over `STEP`, positions first.
fn transition() -> [[f64; 6]; 6] {
    let mut stm = [[0.0; 6]; 6];
    for i in 0..6 {
        stm[i][i] = 1.0;
    }
    for axis in 0..3 {
        stm[axis][axis + 3] = STEP;
    }
    stm
}

fn run(estimator: &Estimator, contamination: f64, outlier_sigmas: f64, seed: u64) -> Report {
    let stm = transition();
    let q = state_noise_compensation(STEP, [ACCELERATION_DENSITY; 3]).unwrap();
    let sq = process_noise_sqrt(&q).unwrap();
    let noise_variance = OBSERVATION_SIGMA * OBSERVATION_SIGMA * estimator.noise_scale;
    let outlier = outlier_sigmas * OBSERVATION_SIGMA;

    let mut initial = [[0.0; 6]; 6];
    for axis in 0..3 {
        initial[axis][axis] = POSITION_SIGMA_0;
        initial[axis + 3][axis + 3] = VELOCITY_SIGMA_0;
    }

    let mut source = Gaussian::seeded(seed);
    let mut tally = [RobustTally::default(); 3];
    let (mut squared_error, mut nees_total, mut samples) = (0.0, 0.0, 0usize);

    for _ in 0..RUNS {
        let mut truth = [0.0, 0.0, 0.0, 7_500.0, -1_200.0, 300.0];
        let mut x0 = truth;
        for axis in 0..3 {
            x0[axis] += POSITION_SIGMA_0 * source.normal();
            x0[axis + 3] += VELOCITY_SIGMA_0 * source.normal();
        }
        let mut filter = SquareRootKalman::new(x0, initial);

        for _ in 0..STEPS {
            // Truth: the same discrete model the filter assumes, so the filter is exactly specified.
            let draw: [f64; 6] = core::array::from_fn(|_| source.normal());
            let mut next = [0.0; 6];
            for i in 0..6 {
                for k in 0..6 {
                    next[i] += stm[i][k] * truth[k];
                }
                // `sq` is the lower Cholesky factor of `Q`, so `sq · draw` has covariance `Q`.
                for k in 0..=i {
                    next[i] += sq[i][k] * draw[k];
                }
            }
            truth = next;

            let propagated: [f64; 6] =
                core::array::from_fn(|i| (0..6).map(|k| stm[i][k] * filter.x[k]).sum::<f64>());
            filter.time_update(&stm, &sq);
            filter.x = propagated;

            for axis in 0..3 {
                let mut z = truth[axis] + OBSERVATION_SIGMA * source.normal();
                if source.uniform() < contamination {
                    z += if source.uniform() < 0.5 {
                        outlier
                    } else {
                        -outlier
                    };
                }
                let mut h = [0.0; 6];
                h[axis] = 1.0;
                let innovation = z - filter.x[axis];
                let outcome = robust_update(
                    &mut filter,
                    estimator.policy,
                    &h,
                    innovation,
                    noise_variance,
                );
                tally[axis].record(&outcome);
            }

            let error: [f64; 6] = core::array::from_fn(|i| filter.x[i] - truth[i]);
            squared_error += error[0] * error[0] + error[1] * error[1] + error[2] * error[2];
            nees_total += normalized_squared(&filter.covariance_sqrt(), &error);
            samples += 1;
        }
    }

    let n = samples as f64;
    Report {
        rms: libm::sqrt(squared_error / n),
        nees: nees_total / n,
        rejected: tally
            .iter()
            .map(RobustTally::rejected_fraction)
            .sum::<f64>()
            / 3.0,
        mean_weight: tally.iter().map(RobustTally::mean_weight).sum::<f64>() / 3.0,
        longest_rejection_run: tally.iter().map(|t| t.longest_rejection_run).max().unwrap(),
    }
}

/// The headline table: cost on clean data, benefit on dirty data, for all five estimators.
#[test]
fn robustness_costs_little_when_the_data_is_clean_and_saves_the_filter_when_it_is_not() {
    let names = estimators();
    let mut rms = [[0.0; CONTAMINATION.len()]; 5];
    let mut nees = [[0.0; CONTAMINATION.len()]; 5];
    let mut run_length = [[0u32; CONTAMINATION.len()]; 5];

    println!("                    0 %                1 %                5 %               20 %");
    println!(
        "                 RMS  NEES  run     RMS  NEES  run     RMS  NEES  run     RMS  NEES  run"
    );
    for (e, estimator) in names.iter().enumerate() {
        let mut line = format!("  {:<12}", estimator.name);
        for (c, &contamination) in CONTAMINATION.iter().enumerate() {
            // Seeded by contamination level only: every estimator sees the same realisation.
            let report = run(estimator, contamination, 20.0, 0x5EED_0000 + c as u64);
            rms[e][c] = report.rms;
            nees[e][c] = report.nees;
            run_length[e][c] = report.longest_rejection_run;
            write!(
                line,
                "{:7.2}{:6.1}{:5}  ",
                report.rms, report.nees, report.longest_rejection_run
            )
            .unwrap();
        }
        println!("{line}");
    }
    // 1. On clean data the plain Kalman filter is the best of the five. Optimality is not a slogan.
    for e in 1..5 {
        assert!(
            rms[e][0] >= rms[0][0],
            "{} beat the optimal filter on clean data: {} against {}",
            names[e].name,
            rms[e][0],
            rms[0][0]
        );
    }
    // 2. And the price is at most 3 % in RMS. Measured: 2.19 %, 0.11 %, 1.39 %, 2.43 %.
    for e in 1..5 {
        let loss = rms[e][0] / rms[0][0] - 1.0;
        assert!(
            loss < 0.03,
            "{} costs {:.2} % on clean data",
            names[e].name,
            100.0 * loss
        );
    }
    // 3. The plain filter comes apart, in error and — worse — in confidence.
    assert!(rms[0][3] > 8.0 * rms[0][0], "plain RMS: {:?}", rms[0]);
    assert!(nees[0][3] > 50.0 * nees[0][0], "plain NEES: {:?}", nees[0]);
    // 4. Huber and the Student-t hold, within 6× of their own clean baseline and comfortably under
    //    the plain filter. Measured 5.0× and 5.0×, at 0.59 and 0.60 of plain.
    for e in [3, 4] {
        assert!(
            rms[e][3] < 6.0 * rms[e][0],
            "{} degraded {:?}",
            names[e].name,
            rms[e]
        );
        assert!(
            rms[e][3] < 0.65 * rms[0][3],
            "{} did not save the arc: {} against plain {}",
            names[e].name,
            rms[e][3],
            rms[0][3]
        );
    }
    // 5. And they agree with each other to within 2 % at every contamination level, so the choice
    //    between them is not made on this experiment.
    for c in 0..CONTAMINATION.len() {
        assert!(
            (rms[3][c] / rms[4][c] - 1.0).abs() < 0.02,
            "Huber {:?} against Student-t {:?}",
            rms[3],
            rms[4]
        );
    }
    // 6. The gate locks out: two orders of magnitude worse than doing nothing, and the covariance
    //    contraction that caused it is self-sustaining, so more contamination is not what drives it.
    assert!(
        rms[1][1] > 100.0 * rms[1][0],
        "the gate was expected to lock out: {:?}",
        rms[1]
    );
    assert!(
        run_length[1][1] > 250,
        "lockout means a rejection run of order the arc length, not {:?}",
        run_length[1]
    );
    // 7. …and the run length is the *only* diagnostic that catches it. NEES ranks the locked-out
    //    filter as healthier than the working one.
    assert!(
        nees[1][1] < nees[0][1] && rms[1][1] > 50.0 * rms[0][1],
        "NEES {:?} against RMS {:?}",
        [nees[1][1], nees[0][1]],
        [rms[1][1], rms[0][1]]
    );
    // 8. Inflation is the same threshold without the rejection, and it never locks out — the weight
    //    is never zero, so there is no run to have.
    assert_eq!(run_length[2], [0; CONTAMINATION.len()]);
    // 9. Monotone in contamination for every estimator — no accidental cancellations.
    for e in 0..5 {
        for c in 1..CONTAMINATION.len() {
            assert!(
                rms[e][c] > rms[e][c - 1],
                "{} not monotone: {:?}",
                names[e].name,
                rms[e]
            );
        }
    }
}

/// Repeat the 20 % cell with `3.5σ` outliers instead of `20σ`: robustness buys almost nothing.
///
/// Measured RMS — plain 7.97 m, gate 1172.71 m, inflation 8.00 m, Huber 7.47 m, Student-t 7.74 m. A
/// 6 % gain for Huber, 3 % for the Student-t, and inflation is 0.4 % *worse* than doing nothing.
///
/// The reason is not a defect in any of them. An estimator that down-weights an observation because
/// its innovation is large cannot tell a `3.5σ` outlier from a `3.5σ` draw of the noise, so the same
/// rule that discounts the corruption discounts the clean tail alongside it — and the clean tail is
/// where the information is. Robustness is insurance against gross errors, and it is priced
/// accordingly.
///
/// The gate is the exception, and not in its favour: its failure mode does not depend on the outlier
/// magnitude at all, because it is driven by the state error the first accepted outlier leaves
/// behind rather than by the outliers themselves.
#[test]
fn marginal_outliers_are_not_worth_defending_against() {
    let names = estimators();
    let marginal: Vec<f64> = names
        .iter()
        .map(|estimator| run(estimator, 0.20, 3.5, 0xC0FF_EE00).rms)
        .collect();
    println!("marginal 3.5σ outliers at 20 %: {marginal:?}");

    let plain = marginal[0];
    // Nothing gains more than 10 %, and inflation loses.
    for (e, &value) in marginal.iter().enumerate().skip(2) {
        assert!(
            value > 0.9 * plain,
            "{} claims more than a 10 % gain on marginal outliers: {value} against {plain}",
            names[e].name
        );
    }
    assert!(marginal[2] > plain, "inflation: {marginal:?}");
    assert!(marginal[3] < plain && marginal[4] < plain, "{marginal:?}");
    // The gate fails here too, and by the same two orders of magnitude.
    assert!(marginal[1] > 100.0 * plain, "{marginal:?}");
}

/// Gating is reported, and the report is quantitatively right.
///
/// A filter that silently discards data is the failure this whole module exists to prevent, so the
/// tally has to be accurate enough to act on. At 5 % contamination by `20σ` outliers the 3σ gate
/// should reject the 5 % that are corrupt plus the false-positive rate on the clean 95 % — a
/// two-sided 3σ tail is 0.27 %, so 5.26 % expected against 5.28 % measured.
#[test]
fn the_tally_reports_the_contamination_it_actually_saw() {
    let names = estimators();
    let gate = &names[1];
    let clean = run(gate, 0.0, 20.0, 0x1234);
    // On clean data the gate rejects only its own false positives: a two-sided 3σ tail is 0.270 %,
    // measured 0.290 %.
    assert!(
        (clean.rejected - 0.0027).abs() < 0.0005,
        "false-positive rate {}",
        clean.rejected
    );
    assert!((clean.mean_weight - (1.0 - clean.rejected)).abs() < 1e-12);

    // At 5 % contamination the expected rate is 5 % plus the false positives on the clean 95 %, so
    // 5.26 %. Measured 7.37 % — and the 2.1 % excess is the lockout, not the arithmetic. The rate
    // alone is not enough to notice that; the run length is.
    let dirty = run(gate, 0.05, 20.0, 0x1234);
    let expected = 0.05 + 0.95 * 0.0027;
    assert!(dirty.rejected > expected, "{} ", dirty.rejected);
    assert!(
        dirty.longest_rejection_run > 250,
        "run {}",
        dirty.longest_rejection_run
    );

    // The continuous policies reject nothing and down-weight instead — the distinction the tally has
    // to preserve, and the reason `rejected` and `mean_weight` are separate numbers.
    for estimator in &names[2..] {
        let report = run(estimator, 0.05, 20.0, 0x1234);
        assert_eq!(report.rejected, 0.0, "{} rejected", estimator.name);
        assert_eq!(report.longest_rejection_run, 0);
        assert!(
            report.mean_weight > 0.9,
            "{} mean weight {}",
            estimator.name,
            report.mean_weight
        );
    }

    // And the Student-t is the one policy whose mean weight can exceed 1, because its scale is not
    // its variance: measured 1.048 on clean data.
    let student = run(&names[4], 0.0, 20.0, 0x1234);
    assert!(student.mean_weight > 1.0, "{}", student.mean_weight);
}
