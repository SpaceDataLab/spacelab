def test_gnss_dop_and_propagation_delays():
    re = 6_378_137.0
    r_gps = 26_560_000.0
    rx = [re, 0.0, 0.0]

    def sat(el, az):
        e = math.cos(el) * math.sin(az)
        n = math.cos(el) * math.cos(az)
        u = math.sin(el)
        return [re + r_gps * u, r_gps * e, r_gps * n]

    # One near-zenith satellite plus a ring of four → a well-conditioned geometry.
    sats = [sat(math.radians(85), 0.0)] + [
        sat(math.radians(25), 2 * math.pi * k / 4) for k in range(4)
    ]
    dop = sl.dilution_of_precision(rx, sats)
    assert dop is not None
    gdop, pdop, hdop, vdop, tdop = dop
    assert 1.0 < pdop < 6.0
    assert abs(gdop**2 - pdop**2 - tdop**2) < 1e-6
    assert abs(pdop**2 - hdop**2 - vdop**2) < 1e-6
    # Fewer than four satellites is unsolvable.
    assert sl.dilution_of_precision(rx, sats[:3]) is None

    # Klobuchar ionospheric delay is a positive slant delay.
    d = sl.klobuchar_iono_delay(
        [1e-8, 0.0, 0.0, 0.0],
        [9e4, 0.0, 0.0, 0.0],
        0.5,
        0.3,
        math.radians(30),
        1.0,
        50_400.0,
    )
    assert d > 0.0
    # Saastamoinen zenith hydrostatic delay is ~2.3 m at sea level, mid-latitude.
    ztd = sl.saastamoinen_zenith_delay(1013.25, math.radians(45), 0.0)
    assert 2.28 < ztd < 2.32


def test_gnss_rinex_positions():
    def d19(x):
        mant, exp = f"{x:.12E}".split("E")
        exp = int(exp)
        sign = "-" if x < 0 else " "
        esign = "+" if exp >= 0 else "-"
        return f"{sign}{mant.lstrip('-')}D{esign}{abs(exp):02d}"

    def orbit(a, b, c, d):
        # Four spaces, which is the format's `4X`. It was three until the reader was read against
        # the specification: every fixture here had been written to match the parser's columns
        # rather than the format's, so none of them could ever disagree with it.
        return "    " + d19(a) + d19(b) + d19(c) + d19(d)

    header = "     3.04           RINEX VERSION / TYPE\n" + " " * 60 + "END OF HEADER\n"

    # A GPS record in the format's own columns: sqrt(a) = 5153.65 -> a ~ 26 560 km (medium Earth orbit).
