#!/usr/bin/env python3
"""Generate RKN12(10)17 coefficient constants from the RKN1210 MATLAB source.

Coefficients are the Dormand-El-Mikkawy-Prince (1987) RKN12(10)17 pair, transcribed to ~30 digits
in Rody Oldenhuis' RKN1210 (MATLAB Central / github rodyo/FEX-RKN1210), themselves from the original
rknint.f. Literals are emitted verbatim so the Rust compiler rounds each to the nearest f64 — the
full-precision rule: never truncate a constant by hand.
"""
import pathlib
import re

SRC = pathlib.Path("/tmp/rkn_coeffs.m").read_text()
NUM = re.compile(r"[-+]?\d+\.?\d*e[-+]?\d+")


def grab(label):
    m = re.search(r"^\s*" + re.escape(label) + r"\s*=\s*\[(.*?)\];", SRC, re.DOTALL | re.MULTILINE)
    if not m:
        raise SystemExit(f"not found: {label}")
    return NUM.findall(m.group(1))


c = grab("c")
bhat, bphat, b, bp = grab("Bhat"), grab("Bphat"), grab("B"), grab("Bp")
assert all(len(v) == 17 for v in (c, bhat, bphat, b, bp)), [len(c), len(bhat), len(bphat), len(b), len(bp)]

# A: lower-triangular, row i (2..17) has i-1 entries in columns 0..i-2.
A = [["0.0"] * 17 for _ in range(17)]
for i in range(2, 18):
    m = re.search(rf"A\({i},1:\d+\)\s*=\s*(.*?);", SRC, re.DOTALL)
    if not m:
        raise SystemExit(f"A row {i} not found")
    row = NUM.findall(m.group(1))
    assert len(row) == i - 1, (i, len(row))
    for j, v in enumerate(row):
        A[i - 1][j] = v


def col(name, vals):
    body = ",\n    ".join(vals)
    return f"pub const {name}: [f64; 17] = [\n    {body},\n];\n"


out = ['//! RKN12(10)17 coefficients — machine-generated by `tools/gen_rkn1210.py`, do not edit.',
       '//!',
       '//! Dormand, El-Mikkawy & Prince (1987), transcribed at ~30 digits in RKN1210 (rodyo/FEX-RKN1210)',
       '//! from the original `rknint.f`. Verbatim literals: the compiler rounds each to the nearest f64.',
       '#![allow(clippy::excessive_precision, clippy::unreadable_literal)]', '']
out.append(col("C", c))
out.append(col("BHAT", bhat))   # order-12 position weights (propagated)
out.append(col("BPHAT", bphat)) # order-12 velocity weights (propagated)
out.append(col("B", b))         # order-10 embedded position weights
out.append(col("BP", bp))       # order-10 embedded velocity weights
rows = ",\n    ".join("[" + ", ".join(r) + "]" for r in A)
out.append(f"pub const A: [[f64; 17]; 17] = [\n    {rows},\n];\n")

pathlib.Path("crates/spacelab-propagation/src/rkn1210_consts.rs").write_text("\n".join(out))
print("wrote rkn1210_consts.rs")
print("c[4] =", c[4], "| A[9][4] =", A[9][4], "| BHAT[6] =", bhat[6])
