#!/usr/bin/env python3
"""An independent slanted-edge measurement, as an oracle for `image_quality.rs`.

The ISO 12233 pipeline is short enough that a second implementation is worth more than a second
opinion: bin the pixels by their distance from the fitted edge, difference the profile, transform it.
This one is written from the standard's description in numpy -- numpy's least squares, numpy's
binning, numpy's FFT -- and shares nothing with the Rust it checks except the algorithm.

**Why not iquaflow itself.** The ticket asked for satellogic/iquaflow as the oracle, and it cannot be
installed: version 1.0.1 (the current release) pins `opencv-python==4.4.0.44`, which has no wheel for
any Python this decade, and pulls `GPyOpt`, `sagemaker`, `mlflow` and `torch` for a metric core that
is two hundred lines of numpy. The dependency wall is the finding; the port in `image_quality.rs`
follows their `sharpness_metric.py`, `rer_metric.py` and `snr_metric.py`, and this script is what
stands in for running theirs.

Two conventions differ deliberately, and the fixture records both so the Rust test can check the
difference rather than absorb it:

  * this script differentiates with the centred `[-1, 0, 1]/2h` filter, the common choice, where the
    Rust differences adjacent bins;
  * this script reports the raw transform, where the Rust divides out the two box filters the
    measurement itself applies (`sinc(f h)` each).

At `f = 0.35` cycles/pixel and quarter-pixel bins those two choices differ by 6 %, which is why the
comparison is worth writing down.

    uv run python tools/gen_edge_oracle.py

writes `crates/spacelab-earthvision/tests/fixtures/slanted_edge.txt`.
"""

from __future__ import annotations

import math
from pathlib import Path

import numpy as np
from scipy.special import erf

HEIGHT, WIDTH = 64, 48
SIGMA = 0.8
SLANT = 0.1234
BIN = 0.25
FREQUENCIES = (0.1, 0.25, 0.35, 0.5)
FIXTURE = Path("crates/spacelab-earthvision/tests/fixtures/slanted_edge.txt")


def synthetic_edge() -> np.ndarray:
    """The ideal step convolved with a Gaussian of `SIGMA` pixels, sampled on the pixel grid."""
    y = np.arange(HEIGHT)[:, None]
    x = np.arange(WIDTH)[None, :]
    edge = WIDTH * 0.5 + SLANT * (y - HEIGHT * 0.5)
    return 0.5 * (1.0 + erf((x - edge) / (SIGMA * math.sqrt(2.0))))


def measure(image: np.ndarray) -> tuple[float, float, dict[float, float]]:
    """RER, FWHM and the raw MTF, by the ISO 12233 pipeline."""
    gradient = np.abs(np.gradient(image, axis=1))
    columns = np.arange(WIDTH)
    located = (gradient * columns).sum(axis=1) / gradient.sum(axis=1)
    rows = np.arange(HEIGHT)
    slope, intercept = np.polyfit(rows, located, 1)
    angle = math.atan(slope)

    distance = (
        (columns[None, :] - (intercept + slope * rows[:, None])) * math.cos(angle)
    ).ravel()
    reach = (
        min(intercept + slope * rows.min(), intercept + slope * rows.max())
        * math.cos(angle)
        - 1.0
    )
    reach = min(reach, WIDTH - 2.0 - max(intercept, intercept + slope * (HEIGHT - 1)))
    edges = np.arange(-reach, reach + BIN, BIN)
    index = np.digitize(distance, edges) - 1
    values = image.ravel()
    keep = (index >= 0) & (index < len(edges) - 1)
    counts = np.bincount(index[keep], minlength=len(edges) - 1)
    sums = np.bincount(index[keep], weights=values[keep], minlength=len(edges) - 1)
    esf = sums / counts
    centres = edges[:-1] + BIN * 0.5

    plateau = max(len(esf) // 10, 1)
    low, high = esf[:plateau].mean(), esf[-plateau:].mean()
    esf = (esf - low) / (high - low)

    crossing = np.interp(0.5, esf, centres)
    rer = float(
        np.interp(crossing + 0.5, centres, esf)
        - np.interp(crossing - 0.5, centres, esf)
    )

    lsf = np.gradient(esf, BIN)
    peak = int(np.argmax(lsf))
    left = np.interp(lsf[peak] / 2, lsf[: peak + 1], centres[: peak + 1])
    right = np.interp(-lsf[peak] / 2, -lsf[peak:], centres[peak:])
    fwhm = float(right - left)

    mtf = {}
    for f in FREQUENCIES:
        phase = 2.0 * math.pi * f * (centres - crossing)
        transform = np.sum(lsf * np.exp(-1j * phase))
        mtf[f] = float(abs(transform) / abs(lsf.sum()))
    return rer, fwhm, mtf


def closed_forms() -> tuple[float, float, dict[float, float]]:
    """What a Gaussian point-spread function gives exactly."""
    rer = float(erf(0.5 / (SIGMA * math.sqrt(2.0))))
    fwhm = 2.0 * math.sqrt(2.0 * math.log(2.0)) * SIGMA
    mtf = {f: math.exp(-2.0 * math.pi**2 * SIGMA**2 * f**2) for f in FREQUENCIES}
    return rer, fwhm, mtf


def main() -> None:
    image = synthetic_edge()
    rer, fwhm, mtf = measure(image)
    want_rer, want_fwhm, want_mtf = closed_forms()

    lines = [
        "# Slanted-edge oracle for crates/spacelab-earthvision/src/image_quality.rs.",
        "# GENERATED by tools/gen_edge_oracle.py -- do not edit by hand.",
        f"# A Gaussian point-spread function of sigma = {SIGMA} px on a {SLANT} px/row slant,",
        f"# measured in numpy by the ISO 12233 pipeline with {BIN} px bins and a centred derivative.",
        "# `oracle` is that measurement; `exact` is the closed form for the same Gaussian.",
        f"geometry {HEIGHT} {WIDTH} {SIGMA!r} {SLANT!r}",
        f"oracle_rer {rer!r}",
        f"exact_rer {want_rer!r}",
        f"oracle_fwhm {fwhm!r}",
        f"exact_fwhm {want_fwhm!r}",
    ]
    for f in FREQUENCIES:
        lines.append(f"oracle_mtf {f!r} {mtf[f]!r}")
        lines.append(f"exact_mtf {f!r} {want_mtf[f]!r}")
    # The image itself, so both codes measure the same doubles rather than two evaluations of the
    # same formula in two libm implementations.
    lines.extend("pixels " + " ".join(repr(float(v)) for v in row) for row in image)
    FIXTURE.write_text("\n".join(lines) + "\n")

    print(f"RER  oracle {rer:.6f}  exact {want_rer:.6f}  ({rer / want_rer - 1:+.2%})")
    print(
        f"FWHM oracle {fwhm:.6f}  exact {want_fwhm:.6f}  ({fwhm / want_fwhm - 1:+.2%})"
    )
    for f in FREQUENCIES:
        print(
            f"MTF({f})  oracle {mtf[f]:.6f}  exact {want_mtf[f]:.6f}  "
            f"({mtf[f] / want_mtf[f] - 1:+.2%})"
        )


if __name__ == "__main__":
    main()
