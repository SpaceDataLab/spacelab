def test_ias15_two_body_holds_the_roundoff_floor():
    mu = 3.986004418e14
    r0 = [7_000e3, 0.0, 0.0]
    v0 = [0.0, (mu / 7_000e3) ** 0.5, 0.0]
    eph = sl.propagate_ias15_dense(r0, v0, 6000.0, mu, j2=0.0)
    rf, vf = eph.final_state()
    e0 = norm(v0) ** 2 / 2 - mu / norm(r0)
    ef = norm(vf) ** 2 / 2 - mu / norm(rf)
    assert abs(ef - e0) / abs(e0) < 1e-13, (
        e0,
        ef,
    )  # compensated summation → machine-precision energy
    # after one full circular period the satellite returns to its start, to the f64 floor.
    period = 2 * math.pi * (7_000e3**3 / mu) ** 0.5
    r_end, _ = sl.propagate_ias15_dense(r0, v0, period, mu, j2=0.0).final_state()
    assert norm([r_end[i] - r0[i] for i in range(3)]) < 1.0, norm(
        [r_end[i] - r0[i] for i in range(3)]
    )


def test_drag_decays_the_orbit():
    mu = 3.986004418e14
    r0 = [6_778e3, 0.0, 0.0]  # ~400 km altitude
    v0 = [0.0, (mu / 6_778e3) ** 0.5, 0.0]
    span = 3 * 2 * math.pi * (6_778e3**3 / mu) ** 0.5  # ~3 orbital periods

    def energy(eph, t):
        r, v = eph.eval(t)
        return norm(v) ** 2 / 2 - mu / norm(r)

    # An aggressive ballistic coefficient (drag sail) so the loss dwarfs integration noise.
    drag = sl.propagate_drag_dense(r0, v0, span, 4, 5.0, tol=1e-10)
    geo = sl.propagate_geopotential_dense(r0, v0, span, 4, tol=1e-10)
    # Drag is dissipative: at the same epoch the drag orbit must sit at lower (more negative) energy.
    assert energy(drag, span) < energy(geo, span) - 1.0, (
        energy(drag, span),
        energy(geo, span),
    )
    # And it stays a bound, sane orbit (did not diverge or fall through the Earth over this span).
    rd, _ = drag.eval(span)
    assert 6.0e6 < norm(rd) < 7.0e6, norm(rd)


