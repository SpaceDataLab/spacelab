/// Earth-around-Sun pulsation `ω = 2π / Julian year`, rad/s — Orekit `EARTH_AROUND_SUN_PULSATION`.
pub const EARTH_AROUND_SUN_PULSATION: f64 = TAU / JULIAN_YEAR;
/// Julian year, s — Orekit `Constants.JULIAN_YEAR`.
pub const JULIAN_YEAR: f64 = 3.155_76e7;
/// Solar-irradiance coefficient, J/m³ — Orekit `KnockeRediffusedForceModel.ES_COEFF`.
pub const ES_COEFF: f64 = 4.560_6e-6;
/// Speed of light, m/s — Orekit `Constants.SPEED_OF_LIGHT`.
pub const SPEED_OF_LIGHT: f64 = 2.997_924_58e8;
/// The JPL-SSD astronomical unit, m — Orekit `Constants.JPL_SSD_ASTRONOMICAL_UNIT`.
///
/// This is **not** the IAU-2012 AU of [`crate::ephemeris::ASTRONOMICAL_UNIT`] (`1.495978707e11`): the
/// two differ in the last digits, and Knocke's `Φ = ES_COEFF·c/d²` uses the JPL value. Using the IAU
/// AU here would shift the solar flux in its last figures away from Orekit.
pub const JPL_SSD_ASTRONOMICAL_UNIT: f64 = 1.495_978_706_91e11;

/// First albedo coefficient — Orekit `A0`.
pub const A0: f64 = 0.34;
/// Constant term of the annual albedo coefficient `A1(t)` — Orekit `C0`.
pub const C0: f64 = 0.0;
/// Cosine amplitude of the annual albedo coefficient `A1(t)` — Orekit `C1`.
pub const C1: f64 = 0.10;
/// Sine amplitude of the annual albedo coefficient `A1(t)` — Orekit `C2`.
pub const C2: f64 = 0.0;
/// Second-degree albedo coefficient — Orekit `A2`.
pub const A2: f64 = 0.29;

/// First emissivity coefficient — Orekit `E0`.
pub const E0: f64 = 0.68;
/// Constant term of the annual emissivity coefficient `E1(t)` — Orekit `K0`.
pub const K0: f64 = 0.0;
/// Cosine amplitude of the annual emissivity coefficient `E1(t)` — Orekit `K1`.
pub const K1: f64 = -0.07;
/// Sine amplitude of the annual emissivity coefficient `E1(t)` — Orekit `K2`.
pub const K2: f64 = 0.0;
/// Second-degree emissivity coefficient — Orekit `E2`.
pub const E2: f64 = -0.18;

/// The angular step `Δ` of the Knocke grid — the central-cap half-angle, the crown step, and the
/// azimuthal sector step.
///
/// A newtype rather than a bare `f64` because this value drives *control flow*, not magnitude. Both
/// grid loops advance by `+= Δ`, so `Δ ≤ 0` never advances and the sum never terminates, while
/// `Δ = NaN` makes `Δ < bound` false on the very first test and the force silently evaluates to
/// zero. Neither state is constructible here, and `Δ > 0.0` is already false for `NaN`.
///
/// Positivity is not enough, because `off += Δ` is f64 addition and not the real one: once
/// `Δ < ulp(off)/2` the accumulator stops moving, and the walk then re-evaluates the *same* element
/// until `step_bound` cuts it off — summing one contribution millions of times over rather than
/// integrating the grid the caller asked for. A wrong answer, not a slow one. So `new` also requires
/// that the largest value either walk reaches can still see the step: `τ + Δ > τ`, which puts the
/// floor at `ulp(τ)/2 = 4.44e-16` rad. Below it the type would be promising a grid the arithmetic
/// cannot represent; the azimuthal walk runs to `τ` and the crown walk only to `acos(Rₑ/‖r‖) ≤ π/2`,
/// so the one test covers both.
///
/// That floor is about representability, not cost. At `Δ = 4.44e-16` the grid still holds 2.0e32
/// elements, which no caller can pay for; `step_bound` is what keeps such a walk finite.
///
/// A step coarser than `1.5 Δ ≥ acos(Rₑ/‖r‖)` leaves no crown inside the visible cap and the flux is
/// legitimately zero — that is the model running out of resolution, not a malformed step, and Orekit
/// behaves the same way. At the other end the element count grows as `Δ⁻²`, so a step is bounded
/// below by what the caller is willing to pay, not by this type: the invariant here is that the
/// loops *terminate*, not that they terminate quickly.
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct AngularResolution(f64);

impl AngularResolution {
    /// `None` unless `Δ` is finite and large enough that `off += Δ` still advances at `τ` — the
    /// exact condition under which both grid loops move and their bound comparisons are meaningful.
    #[must_use]
    pub fn new(step: f64) -> Option<Self> {
        (step.is_finite() && TAU + step > TAU).then_some(Self(step))
    }

    /// The step in radians.
    #[must_use]
    pub const fn get(self) -> f64 {
        self.0
    }
}

/// Earth albedo + thermal-IR reradiated radiation pressure on a pluggable [`RadiationModel`], as an
/// inertial-frame [`Acceleration`] for a `Newtonian((…))` composition — Orekit's
/// `KnockeRediffusedForceModel`.
///
/// Mirrors [`crate::spacecraft::PanelSrp`]: it assembles a flux vector (here by summing the Earth
/// grid, not the direct Sun term), rotates it and the satellite→Sun direction into the body frame
/// with `attitude(t)` (inertial→body, `v_body = M·v_inertial`), evaluates the radiation model, and
/// rotates the result back. For an isotropic [`crate::spacecraft::Cannonball`] the model is
/// rotation-invariant and the attitude is immaterial.
pub struct KnockeEarthRadiation<M, R, E> {
    /// The spacecraft radiation model (the same one a direct-SRP force uses).
    pub model: M,
    /// The Sun's position over time (drives both the albedo geometry and the array-normal Sun
    /// direction).
    pub sun: E,
    /// Earth equatorial radius `Rₑ`, m.
    pub equatorial_radius: f64,
    /// Angular resolution `Δ` of the grid (the central-cap half-angle and the crown step).
    pub angular_resolution: AngularResolution,
    /// Seconds from Knocke's reference epoch (1981-12-22T00:00:00 UTC) to the propagation epoch: the
    /// seasonal term uses `Δt = reference_epoch_offset + t`. The caller computes this once at the
    /// boundary (`epoch.durationFrom(1981-12-22)`), keeping all time-scale machinery out of the crate.
    pub reference_epoch_offset: f64,
    /// Inertial→body attitude matrix at time `t` (`v_body = M·v_inertial`).
    pub attitude: R,
}

impl<M, R, E> Acceleration for KnockeEarthRadiation<M, R, E>
where
    M: RadiationModel,
    R: Fn(f64) -> [[f64; 3]; 3],
    E: Ephemeris,
{
    fn acceleration<S: Scalar>(&self, t: S, r: &[S; 3], _v: &[S; 3]) -> [S; 3] {
        let flux = self.rediffused_flux(t.value(), r);
        let m = (self.attitude)(t.value());
        let sun_dir = unit_sun_dir(&self.sun, t.value(), r);
        let a_body = self
            .model
            .radiation(&to_body(&m, &flux), &to_body(&m, &sun_dir));
        to_inertial(&m, &a_body)
    }
}

impl<M, R, E: Ephemeris> KnockeEarthRadiation<M, R, E> {
    /// The total rediffused (albedo + IR) flux vector at the satellite, in the inertial frame — the
    /// grid sum of Orekit's `KnockeRediffusedForceModel.acceleration` with each element weighted by
    /// its emission angle, before the spacecraft model is applied. Exposed for validation.
    #[must_use]
    pub fn rediffused_flux<S: Scalar>(&self, t: f64, r: &[S; 3]) -> [S; 3] {
        self.grid_sum(t, r, Grid::Lambert)
    }

    fn grid_sum<S: Scalar>(&self, t: f64, r: &[S; 3], grid: Grid) -> [S; 3] {
        let re = self.equatorial_radius;
        let ares = self.angular_resolution.get();

        // Sun geometry (position-independent → f64, lifted once).
        let sun_f = self.sun.position(t);
        if crate::ephemeris::is_absent(sun_f) {
            return [S::from_f64(0.0); 3];
        }
        let sun = [
            S::from_f64(sun_f[0]),
            S::from_f64(sun_f[1]),
            S::from_f64(sun_f[2]),
        ];
        let sun_norm = libm::sqrt(sun_f[0] * sun_f[0] + sun_f[1] * sun_f[1] + sun_f[2] * sun_f[2]);
        let earth_sun_au = sun_norm / JPL_SSD_ASTRONOMICAL_UNIT;
        let solar_flux = ES_COEFF * SPEED_OF_LIGHT / (earth_sun_au * earth_sun_au);

        // Annual (seasonal) first-order coefficients — functions of time alone.
        let delta_t = self.reference_epoch_offset + t;
        let phase = EARTH_AROUND_SUN_PULSATION * delta_t;
        let (sin_ph, cos_ph) = (libm::sin(phase), libm::cos(phase));
        let a1 = C0 + C1 * cos_ph + C2 * sin_ph;
        let e1 = K0 + K1 * cos_ph + K2 * sin_ph;

        let exitance =
            |center: &[S; 3]| knocke_exitance(center, &sun, sun_norm, solar_flux, a1, e1);
        match grid {
            Grid::Lambert => walk(re, ares, r, exitance),
            #[cfg(test)]
            Grid::Orekit => orekit_walk(re, ares, r, exitance),
        }
    }
}

/// The flux of the sphere of radius `re` seen from `r`, each point radiating `exitance(point)`
/// (already divided by `c`) by Lambert's law. The visible cap is cut into the central cap of
/// half-angle `Δ` and crowns of width `Δ` out to the horizon, the last one cut at it, and the Lambert
/// kernel is integrated exactly over each: a crown's flux along `r̂` is the difference of two caps'
/// view factors ([`cap_view_factor`]). A crown is split into `n = ⌈2π/Δ⌉` equal sectors; each radiates
/// at its centre's exitance along its centre's ray `r − p`, scaled so that its share of the crown's
/// flux along `r̂` is exact. A uniform sphere then sums to `(R/r)²` to a rounding, and on a varying
/// exitance the error is the exitance's and the ray's variation across a sector.
fn walk<S: Scalar, F: Fn(&[S; 3]) -> S>(re: f64, ares: f64, r: &[S; 3], exitance: F) -> [S; 3] {
    // Satellite geometry.
    let r_norm = dot3(r, r).sqrt();
    let inv_r_norm = r_norm.recip();
    // projectedToGround = r̂·Rₑ — the sub-satellite point on the sphere.
    let pg_scale = S::from_f64(re) * inv_r_norm;
    let projected = [r[0] * pg_scale, r[1] * pg_scale, r[2] * pg_scale];
    // east = (−rᵧ, rₓ, 0), across `r` — the first crown axis. [`rotate_by`] divides by its norm.
    let east = [-r[1], r[0], S::from_f64(0.0)];

    // The central cap, at its centre's exitance. Orekit lumps the cap's whole area at its centre,
    // which is only the first, `Δ²`, term of its integral (`derivations/knocke_lambert.mac` (5)):
    // 13× the exact flux at Δ = 15° and 51× at 30°, at 500 km.
    let mut inner = cap_view_factor(re, ares, r_norm);
    let along = inner * exitance(&projected) * inv_r_norm;
    let mut flux = [r[0] * along, r[1] * along, r[2] * along];

    // The crowns. The bounds and every angle are taken from the f64 value: the crown count is a
    // step function of position (the STM's shadow-gate analogue).
    let horizon = libm::acos(re / r_norm.value());
    let sectors = libm::ceil(TAU / ares);
    let sector_step = TAU / sectors;
    let sector_share = S::from_f64(sectors.recip()) * r_norm;
    let mut crowns_left = step_bound(ares, horizon, ares);
    let mut lower = ares;
    while lower < horizon && crowns_left > 0 {
        crowns_left -= 1;
        let upper = lower + ares;
        // Past the horizon a cap's view factor is `(R/r)²`, so the last crown ends there.
        let outer = cap_view_factor(re, upper, r_norm);
        let share = (outer - inner) * sector_share;
        let first_center = if upper < horizon {
            rotate_vector(&east, 0.5 * (lower + upper), &projected)
        } else {
            // The last crown's middle follows the horizon as `r` moves, so its colatitude carries
            // derivatives: the horizon is atan2(√(r² − R²), R).
            let edge = ((r_norm - S::from_f64(re)) * (r_norm + S::from_f64(re)))
                .sqrt()
                .atan2(S::from_f64(re));
            let half = (S::from_f64(lower) + edge) * S::from_f64(-0.25);
            rotate_by(&east, half.sin(), half.cos(), &projected)
        };
        let mut azimuth = 0.5 * sector_step;
        for _ in 0..sector_count(sectors) {
            let center = rotate_vector(&projected, azimuth, &first_center);
            let ray = [r[0] - center[0], r[1] - center[1], r[2] - center[2]];
            // ray·r = r² − r R cos θ > 0 for every point of the sphere, so the scale is finite.
            let scale = share * exitance(&center) / dot3(&ray, r);
            flux = [
                flux[0] + ray[0] * scale,
                flux[1] + ray[1] * scale,
                flux[2] + ray[2] * scale,
            ];
            azimuth += sector_step;
        }
        inner = outer;
        lower = upper;
    }
    flux
}

/// Orekit 13.1.7's grid, element for element: the cap lumped at its centre, then crowns at
/// colatitudes `1.5Δ, 2.5Δ, …` while their centres lie below the horizon, each swept in azimuth by
/// steps of `Δ`, with [`elementary_flux`]'s cosine.
#[cfg(test)]
fn orekit_walk<S: Scalar, F: Fn(&[S; 3]) -> S>(
    re: f64,
    ares: f64,
    r: &[S; 3],
    exitance: F,
) -> [S; 3] {
    let r_norm = dot3(r, r).sqrt();
    let inv_r_norm = r_norm.recip();
    let pg_scale = S::from_f64(re) * inv_r_norm;
    let projected = [r[0] * pg_scale, r[1] * pg_scale, r[2] * pg_scale];
    let q = (r[0] * r[0] + r[1] * r[1]).sqrt().recip();
    let east = [-(q * r[1]), q * r[0], S::from_f64(0.0)];

    let center_area = TAU * re * re * (1.0 - libm::cos(ares));
    let mut flux = elementary_flux(r, &projected, center_area, exitance(&projected));

    let cap_limit = libm::acos(re / r_norm.value());
    let re2 = re * re;
    let sector_bound = step_bound(0.5 * ares, TAU, ares);
    let mut crowns_left = step_bound(1.5 * ares, cap_limit, ares);
    let mut east_off = 1.5 * ares;
    while east_off < cap_limit && crowns_left > 0 {
        crowns_left -= 1;
        let first_center = rotate_vector(&east, east_off, &projected);
        let sector_area = re2 * 2.0 * ares * libm::sin(0.5 * ares) * libm::sin(east_off);
        let mut sectors_left = sector_bound;
        let mut radial_off = 0.5 * ares;
        while radial_off < TAU && sectors_left > 0 {
            sectors_left -= 1;
            let center = rotate_vector(&projected, radial_off, &first_center);
            let df = elementary_flux(r, &center, sector_area, exitance(&center));
            flux = [flux[0] + df[0], flux[1] + df[1], flux[2] + df[2]];
            radial_off += ares;
        }
        east_off += ares;
    }
    flux
}

/// `⌈2π/Δ⌉` as a count. The cast saturates, so a step too fine to pay for gives `usize::MAX`, a
/// walk that is finite though nobody waits for it, as [`step_bound`] allows.
#[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
fn sector_count(sectors: f64) -> usize {
    sectors as usize
}

/// An upper bound on how many steps of `step` from `start` can stay strictly below `bound`.
///
/// The grid walks are `off += step` until `off < bound` fails, and `off > 0` is a termination proof
/// in ℝ, not in f64: once `step < ulp(off)/2` the sum stops advancing, so for `step ≲ bound·2⁻⁵³` it
/// plateaus below its bound and the walk never ends. [`AngularResolution`] now rejects those steps
/// at construction, which is the honest place for it, so this is a second line and not the only one:
/// it also bounds a walk whose step is representable but unpayable, where the `<` test would
/// eventually fire after 1e16 passes nobody is waiting for.
///
/// A bound, not a count: the walks keep their own `<` test, which stays authoritative because a
/// closed-form ratio and an accumulated sum disagree by an ulp on exactly the boundaries the grid is
/// pinned at. `+ 1` covers that disagreement in the safe direction. The `f64 → usize` cast
/// saturates, so an unreachable or NaN bound gives `0` and an unpayable one `usize::MAX`.
#[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
fn step_bound(start: f64, bound: f64, step: f64) -> usize {
    (libm::ceil((bound - start) / step) as usize).saturating_add(1)
}

/// Which grid sums the sphere.
#[derive(Clone, Copy)]
enum Grid {
    /// Lambert's law, each piece's kernel integrated exactly: [`walk`].
    Lambert,
    /// Orekit 13.1.7's grid and cosine, kept so the sum can still be compared with Orekit's
    /// element for element: [`orekit_walk`].
    #[cfg(test)]
    Orekit,
}

/// The exact Lambert view factor, along `r̂`, of the sphere's cap of half-angle `Δ` about the
/// sub-satellite point, cut at the horizon: `R² sin²Δ / d²`, `d` the distance from the satellite to
/// the cap's rim, and `(R/r)²` once the cap reaches the horizon (`derivations/knocke_lambert.mac` (5)).
/// The rim distance is `d² = (r − R)² + 4 r R sin²(Δ/2)`, free of the cancellation in
/// `r² + R² − 2 r R cos Δ`. Which branch applies is read from the value, as the crown count is.
fn cap_view_factor<S: Scalar>(re: f64, half_angle: f64, r_norm: S) -> S {
    let ratio = S::from_f64(re) / r_norm;
    if libm::cos(half_angle) <= ratio.value() {
        return ratio * ratio;
    }
    let half = libm::sin(0.5 * half_angle);
    let rim = (r_norm - S::from_f64(re)) * (r_norm - S::from_f64(re))
        + S::from_f64(4.0 * re * half * half) * r_norm;
    let s = libm::sin(half_angle);
    S::from_f64(re * re * s * s) / rim
}

/// One element of Orekit 13.1.7's grid — a port of its `computeElementaryFlux` (the `double`
/// path). `sat` and `center` are inertial (satellite position and the element centre on the sphere),
/// `area` the element's area and `exitance` what it radiates, divided by `c`. The flux is
/// `area·cos α/(π |r − p|³)` times the exitance, along `r − p`, or zero if the satellite cannot see
/// the area. Orekit takes `cos α` between the element's normal and the satellite's geocentric
/// position, not the ray from the element: that is not Lambert's law.
#[cfg(test)]
fn elementary_flux<S: Scalar>(sat: &[S; 3], center: &[S; 3], area: f64, exitance: S) -> [S; 3] {
    let center_norm = dot3(center, center).sqrt();
    let rv = [sat[0] - center[0], sat[1] - center[1], sat[2] - center[2]];
    let rn = dot3(&rv, &rv).sqrt();
    let cos_alpha = dot3(center, sat) / (center_norm * dot3(sat, sat).sqrt());

    // Horizon gate on the value — a measure-zero boundary the STM is not defined across.
    if cos_alpha.value() <= 0.0 {
        return [S::from_f64(0.0); 3];
    }

    // Lambert/inverse-square projected area, along r = sat − center.
    let scale = S::from_f64(area) * cos_alpha / (S::from_f64(PI) * rn * rn * rn) * exitance;
    [rv[0] * scale, rv[1] * scale, rv[2] * scale]
}

/// Knocke's exitance at an element, divided by `c`: the albedo `a Φ cos θ☉` on the daylit side and
/// the infrared `e Φ/4` everywhere, with the zonal coefficients of the element's latitude. `sun` and
/// `sun_norm` are the inertial Sun, `solar_flux` `Φ` at Earth, `a1` and `e1` the annual coefficients.
fn knocke_exitance<S: Scalar>(
    center: &[S; 3],
    sun: &[S; 3],
    sun_norm: f64,
    solar_flux: f64,
    a1: f64,
    e1: f64,
) -> S {
    let center_norm = dot3(center, center).sqrt();

    // Latitude sinus: sinφ = sin(asin(z/|p|)) = z/|p| (the round-trip is exact to a rounding).
    let sin_phi = center[2] / center_norm;
    // Legendre P1(x) = x, P2(x) = 1.5·x² − 0.5.
    let p1 = sin_phi;
    let p2 = S::from_f64(1.5) * sin_phi * sin_phi - S::from_f64(0.5);
    let emissivity = S::from_f64(E0) + S::from_f64(e1) * p1 + S::from_f64(E2) * p2;

    // Albedo only on the daylit side (cosθ☉ > 0), taken from the value.
    let cos_sun = dot3(center, sun) / (center_norm * S::from_f64(sun_norm));
    let albedo = if cos_sun.value() > 0.0 {
        S::from_f64(A0) + S::from_f64(a1) * p1 + S::from_f64(A2) * p2
    } else {
        S::from_f64(0.0)
    };

    let sf = S::from_f64(solar_flux);
    let albedo_and_ir = albedo * sf * cos_sun + emissivity * sf * S::from_f64(0.25);
    albedo_and_ir / S::from_f64(SPEED_OF_LIGHT)
}

/// Rotate `u` about `axis` by `angle` (rad) — a verbatim port of Hipparchus
/// `Rotation(axis, angle, RotationConvention.VECTOR_OPERATOR).applyTo(u)`, the rotation the Knocke
/// grid uses to place ring/sector centres. The half-angle is negated for the `VECTOR_OPERATOR`
/// convention (a right-handed active rotation of the vector), and `axis` need not be unit — its norm
/// divides the quaternion vector part exactly as Hipparchus does.
///
/// `angle` is an `f64` grid constant; only `axis` and `u` (built from the satellite position) carry
/// derivatives, so the quaternion arithmetic threads the STM through.
#[must_use]
pub fn rotate_vector<S: Scalar>(axis: &[S; 3], angle: f64, u: &[S; 3]) -> [S; 3] {
    let half = -0.5 * angle; // VECTOR_OPERATOR convention
    rotate_by(
        axis,
        S::from_f64(libm::sin(half)),
        S::from_f64(libm::cos(half)),
        u,
    )
}

/// [`rotate_vector`] given the sine and cosine of its negated half-angle, so that the angle may
/// carry derivatives too.
fn rotate_by<S: Scalar>(axis: &[S; 3], sin_half: S, cos_half: S, u: &[S; 3]) -> [S; 3] {
    let norm = dot3(axis, axis).sqrt();
    let coeff = sin_half / norm;
    let q0 = cos_half;
    let q1 = coeff * axis[0];
    let q2 = coeff * axis[1];
    let q3 = coeff * axis[2];
    let (x, y, z) = (u[0], u[1], u[2]);
    let s = q1 * x + q2 * y + q3 * z;
    let two = S::from_f64(2.0);
    [
        two * (q0 * (x * q0 - (q2 * z - q3 * y)) + s * q1) - x,
        two * (q0 * (y * q0 - (q3 * x - q1 * z)) + s * q2) - y,
        two * (q0 * (z * q0 - (q1 * y - q2 * x)) + s * q3) - z,
    ]
}

