#= Validated enclosures of three short arcs, the test vectors every integrator in
   spacelab-propagation is held to (plans/17 Ф28.H).

   TaylorModels.jl integrates the flow with Taylor models in time and returns, at the end of the
   arc, an interval box that contains the exact solution from the given initial state (Benet,
   Forets, Sanders & Schilling 2019, Commun. Nonlinear Sci. Numer. Simul. 79, 104410). The
   systems are dimensionless, so every state is of order one:

       kepler   two-body, mu = 1, from periapsis at e = 0.1, one period (t = 2 pi)
       j2       two-body + J2, mu = 1, R = 1, from r = 1.1 at 51.6 degrees, about one period
       halo     the Earth-Moon CR3BP, from the L1 halo `periodic::richardson_halo(EARTH_MOON, 0,
                0.2, true)` returns, over the period it returns

   A seventh state, tau' = 1, carries the time. TaylorModels adds the steps in floating point, so
   the box belongs to the time the steps sum to, which tau encloses; the script refuses an arc
   whose tau is not exactly the requested end time.

   F52: TaylorModels.jl before 0.13.0 reset each step's remainder to zero, and IntervalArithmetic.jl
   before 1.0.12 did not round `radius` outward. The script refuses both, and TaylorIntegration.jl
   before 0.18.19. The packages are not a dependency of the repository; any environment that holds
   them runs it:

       cd derivations && timeout 1800 julia --startup-file=no --project=<env> taylor_model_enclosures.jl

   It writes crates/spacelab-propagation/tests/fixtures/taylor_model_enclosures.txt. Every number
   there is an IEEE-754 bit pattern as a decimal u64, so the Rust test and
   taylor_model_enclosures.mac read the same doubles. That file checks the kepler box against the
   exact solution, and derives from their potentials the j2 and halo vector fields that this
   script and the Rust test code.                                                                 =#

using TaylorModels
using TaylorModels.ValidatedInteg
using Printf

const TI = TaylorIntegration

pkgversion(TaylorModels) >= v"0.13.0" ||
    error("TaylorModels.jl < 0.13.0 drops remainders (F52)")
pkgversion(IntervalArithmetic) >= v"1.0.12" || error("IntervalArithmetic.jl < 1.0.12 (F52)")
pkgversion(TaylorIntegration) >= v"0.18.19" || error("TaylorIntegration.jl < 0.18.19 (F52)")

const J2 = 1.0826266835531513e-3
const MU = 0.012150584460351

TI.@taylorize2 function kepler!(dx, x, p, t)
    r2 = x[1]^2 + x[2]^2 + x[3]^2
    r3inv = 1 / (r2 * sqrt(r2))
    dx[1] = x[4]
    dx[2] = x[5]
    dx[3] = x[6]
    dx[4] = -x[1] * r3inv
    dx[5] = -x[2] * r3inv
    dx[6] = -x[3] * r3inv
    dx[7] = one(x[7])
    nothing
end

TI.@taylorize2 function j2!(dx, x, p, t)
    r2 = x[1]^2 + x[2]^2 + x[3]^2
    r3inv = 1 / (r2 * sqrt(r2))
    s = 1.5 * J2 / r2
    q = 5 * x[3]^2 / r2
    dx[1] = x[4]
    dx[2] = x[5]
    dx[3] = x[6]
    dx[4] = -x[1] * r3inv * (1 + s * (1 - q))
    dx[5] = -x[2] * r3inv * (1 + s * (1 - q))
    dx[6] = -x[3] * r3inv * (1 + s * (3 - q))
    dx[7] = one(x[7])
    nothing
end

TI.@taylorize2 function halo!(dx, x, p, t)
    d1 = x[1] + MU
    d2 = x[1] - 1 + MU
    r1s = d1^2 + x[2]^2 + x[3]^2
    r2s = d2^2 + x[2]^2 + x[3]^2
    a1 = (1 - MU) / (r1s * sqrt(r1s))
    a2 = MU / (r2s * sqrt(r2s))
    dx[1] = x[4]
    dx[2] = x[5]
    dx[3] = x[6]
    dx[4] = x[1] + 2 * x[5] - a1 * d1 - a2 * d2
    dx[5] = x[2] - 2 * x[4] - a1 * x[2] - a2 * x[2]
    dx[6] = -a1 * x[3] - a2 * x[3]
    dx[7] = one(x[7])
    nothing
end

const CASES = [
    ("kepler", kepler!, [0.9, 0.0, 0.0, 0.0, sqrt(1.1 / 0.9), 0.0], 2π),
    ("j2", j2!, [1.1, 0.0, 0.0, 0.0, 0.5925, 0.7471], 7.25),
    (
        "halo",
        halo!,
        [0.8234486511634148, 0.0, 0.03246291668416727, 0.0, 0.14215131563336936, 0.0],
        2.7499364151985937,
    ),
]

"The box that contains the exact state at `t1`, from the exact initial state `q0`."
function enclose(f!, q0::Vector{Float64}, t1::Float64)
    x0 = [interval(v) for v in vcat(q0, 0.0)]
    space = JetSpace(2, ["ξ$i" for i = 1:7])
    sol = validated_integ(f!, x0, 0.0, t1, 1, 25, 1e-22, space; maxsteps = 20_000)
    last = sol[lastindex(sol)]
    at_end = interval(sup(domain(last[1])))
    box = evaluate.(evaluate.(last, at_end), Ref(Vector(symmetric_box(7))))
    tau = box[7]
    inf(tau) == sup(tau) == t1 ||
        error("the arc ends at tau = [$(inf(tau)), $(sup(tau))], not at $t1")
    all(isbounded, box) || error("an unbounded enclosure")
    return box[1:6], length(sol)
end

bits(v::Float64) = string(reinterpret(UInt64, v))

function main()
    out = joinpath(
        @__DIR__,
        "..",
        "crates",
        "spacelab-propagation",
        "tests",
        "fixtures",
        "taylor_model_enclosures.txt",
    )
    open(out, "w") do io
        println(
            io,
            "# Generated by derivations/taylor_model_enclosures.jl with TaylorModels.jl ",
            pkgversion(TaylorModels),
            ", IntervalArithmetic.jl ",
            pkgversion(IntervalArithmetic),
            " and TaylorIntegration.jl ",
            pkgversion(TaylorIntegration),
            ". Do not edit.",
        )
        println(io, "# Each value is an IEEE-754 double as its bit pattern, a decimal u64.")
        println(io, "# lo and hi bound the exact state at t1 from the exact state ic.")
        for (name, f!, q0, t1) in CASES
            box, steps = enclose(f!, q0, t1)
            width = maximum(sup(b) - inf(b) for b in box)
            @printf("%-7s %3d steps, widest component %.3e\n", name, steps, width)
            println(io, "case ", name)
            println(io, "ic ", join(bits.(q0), ' '))
            println(io, "t1 ", bits(t1))
            println(io, "lo ", join(bits.(inf.(box)), ' '))
            println(io, "hi ", join(bits.(sup.(box)), ' '))
        end
    end
    println("wrote ", normpath(out))
end

main()
