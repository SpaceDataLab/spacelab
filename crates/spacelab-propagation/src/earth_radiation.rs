    /// Earth radiation pushes the satellite *outward* — the reradiated flux comes from below, so the
    /// acceleration has a positive radial component `a·r̂ > 0` at any epoch/geometry. A model-level
    /// sanity independent of the golden numbers.
    #[test]
    fn earth_radiation_pushes_outward() {
        let sat = [6.9e6, 1.1e6, 2.3e6];
        let force = KnockeEarthRadiation {
            model: model(),
            sun: FixedBody([1.2e11, -0.8e11, -0.4e11]),
            equatorial_radius: AE,
            angular_resolution: step(ARES),
            reference_epoch_offset: 1.33e9,
            attitude: |_t: f64| IDENTITY,
        };
        let a = force.acceleration(0.0, &sat, &[0.0; 3]);
        let r_norm = (sat[0] * sat[0] + sat[1] * sat[1] + sat[2] * sat[2]).sqrt();
        let radial = (a[0] * sat[0] + a[1] * sat[1] + a[2] * sat[2]) / r_norm;
        assert!(
            radial > 0.0,
            "Earth radiation must push outward: a·r̂ = {radial:.3e}"
        );
        assert!(
            a[0].abs() + a[1].abs() + a[2].abs() > 0.0,
            "acceleration must be non-zero"
        );
    }

    /// The grid step is the one field whose value decides *control flow* rather than magnitude, and
    /// both hazards it used to carry are now unconstructible. `Δ ≤ 0` never advanced `east_off += Δ`
    /// and the sum ran forever — cargo-mutants found it by timing out on `+= → *=` and `+= → -=` at
    /// both loops, which is the same mutation surviving as a hang rather than as a wrong number.
    /// `Δ = NaN` was worse than a hang: `east_off < cap_limit` is false for a NaN left operand, so
    /// the grid was empty on the first test and the force returned exactly zero — a silently absent
    /// perturbation. `τ + Δ > τ` is already false for `NaN` and for every negative including `−0.0`,
    /// and `is_finite` removes `+∞`, so one test closes both — and a third hazard the campaign found
    /// after them, the step too small for the accumulator to see, which
    /// [`the_grid_walks_are_bounded_where_the_sum_stops_climbing`] takes apart on its own.
    #[test]
    fn only_a_finite_positive_grid_step_is_constructible() {
        for bad in [
            0.0,
            -0.0,
            -ARES,
            -PI,
            f64::NAN,
            f64::INFINITY,
            f64::NEG_INFINITY,
        ] {
            assert!(
                AngularResolution::new(bad).is_none(),
                "{bad:?} was accepted as a grid step"
            );
        }
        // The boundary of the domain, not a recommendation: the element count grows as Δ⁻².
        for good in [min_visible_step(), 1e-6, ARES, PI, f64::MAX] {
            assert_eq!(
                AngularResolution::new(good).map(AngularResolution::get),
                Some(good),
                "{good:?} was rejected as a grid step"
            );
        }
    }

    /// A positive step is not enough to make `off += Δ` reach its bound. Once `Δ < ulp(off)/2` the
    /// sum stops climbing: at `Δ = 1e-17` the azimuth accumulator plateaus at exactly `0.125`, well
    /// short of `2π`. That is worse than slow — the walk keeps re-evaluating the element at the
    /// plateau, so the flux it returns is one contribution counted [`step_bound`]-many times, and
    /// the `while radial_off < TAU` alone could not end it for any input, mutated or not.
    ///
    /// Two things answer it, and they answer different halves. `AngularResolution::new` refuses the
    /// step outright, which is where it belongs: `ULP_TAU_HALF` is the smallest one the accumulator
    /// can see, and every value below it is rejected while the boundary itself is kept. And
    /// [`step_bound`] still caps both walks, for the steps that *are* representable and still ask
    /// for more passes than anyone will wait through.
    #[test]
    #[allow(clippy::float_cmp)] // the plateau is bit-exact, which is the whole claim
    fn the_grid_walks_are_bounded_where_the_sum_stops_climbing() {
        let stuck = 1.0e-17;
        let plateau = 0.125;
        assert_eq!(
            plateau + stuck,
            plateau,
            "the accumulator can climb no further"
        );
        assert!(
            plateau < TAU,
            "and it plateaus below the bound it is chasing"
        );
        assert!(
            AngularResolution::new(stuck).is_none(),
            "so the constructor must not hand it out"
        );
        // The floor is exactly where the accumulator stops seeing the step, and it is one-sided.
        // `ulp(τ)/2` is `2·EPSILON`, but round-to-nearest-*even* takes that tie back down, so the
        // half-ulp itself leaves τ unmoved and the floor is the float one above it.
        let half_ulp = 2.0 * f64::EPSILON;
        assert_eq!(TAU + half_ulp, TAU, "the tie rounds down");
        assert!(
            TAU + min_visible_step() > TAU,
            "the float above it does not"
        );
        assert!(AngularResolution::new(min_visible_step()).is_some());
        assert!(AngularResolution::new(half_ulp).is_none());
        assert!(
            step_bound(0.5 * stuck, TAU, stuck) < usize::MAX,
            "and a walk that did start is still bounded"
        );

        // And the bound never truncates a walk the `<` test would have allowed.
        for &ares in &[ARES, 1e-3, 2.0 * PI / 28.5] {
            let (mut off, mut taken) = (0.5 * ares, 0usize);
            while off < TAU {
                off += ares;
                taken += 1;
            }
            assert!(
                taken <= step_bound(0.5 * ares, TAU, ares),
                "Δ = {ares}: {taken} steps"
            );
        }
    }

