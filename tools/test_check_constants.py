#!/usr/bin/env python3
"""The constants sweep's literal, item, test-region and citation rules, on hand-made inputs.

uv run --no-project python -I tools/test_check_constants.py
"""

from __future__ import annotations

import importlib.util
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location(
    "check_constants", HERE / "check-constants.py"
)
assert spec is not None and spec.loader is not None
tool = importlib.util.module_from_spec(spec)
sys.modules["check_constants"] = tool
spec.loader.exec_module(tool)


def long_literals(line: str) -> list[str]:
    code, _ = tool.code_of(line)
    return [t for t in tool.NUMBER.findall(code) if tool.significant(t) > tool.DIGITS]


def test_significant_digits_skip_separators_signs_and_padding_zeros() -> None:
    assert tool.significant("6_378_137.0") == 7
    assert tool.significant("0.000_123_456_7") == 7
    assert tool.significant("1.380_649e-23") == 7
    assert tool.significant("1.5e14") == 2
    assert tool.significant("100000000.0") == 1


def test_a_literal_is_not_a_field_a_name_a_string_or_a_comment() -> None:
    assert long_literals("let x = 2.997_924_58e8_f64;") == ["2.997_924_58e8"]
    assert long_literals("let y = t.0 + v2.1234567;") == []
    assert long_literals('let s = "3.14159265";') == []
    assert long_literals("let z = 1.0; // 3.14159265") == []
    assert long_literals("let w = 12_345_678;") == []


def test_a_cfg_test_item_is_skipped_to_its_closing_brace() -> None:
    lines = [
        "const A: f64 = 1.234_567_89;",
        "#[cfg(test)]",
        "mod tests {",
        '    const S: &str = "}";',
        "    fn f() { let b = 9.876_543_21; }",
        "}",
        "const C: f64 = 2.345_678_91;",
    ]
    assert tool.test_lines(lines) == {1, 2, 3, 4, 5}


def test_an_attribute_belongs_to_the_item_below_it() -> None:
    lines = [
        "fn before() {}",
        "",
        "/// Defaults from the IERS Conventions.",
        "#[pyo3(signature = (",
        "    mu = 3.986_004_418e14,",
        "))]",
        "fn bound(mu: f64) {}",
    ]
    owner = tool.owners(lines, set())
    assert owner[4] == ("bound", "/// Defaults from the IERS Conventions.")
    assert owner[0][0] == "before"


def test_an_extern_c_function_is_an_item() -> None:
    lines = [
        "const LIMIT: usize = 8;",
        "",
        "#[unsafe(no_mangle)]",
        'pub unsafe extern "C" fn sl_init(p: *mut f64) {',
        "    unsafe { *p = 3.986_004_418e14 };",
        "}",
    ]
    owner = tool.owners(lines, set())
    assert owner[4][0] == "sl_init"


def test_a_run_of_items_shares_the_comment_above_its_first() -> None:
    lines = [
        "// Generated by derivations/x.gp.",
        "#[rustfmt::skip]",
        "const P: [f64; 1] = [0.123_456_789];",
        "#[rustfmt::skip]",
        "const W: [f64; 1] = [0.987_654_321];",
        "",
        "const Z: f64 = 0.111_111_111;",
    ]
    owner = tool.owners(lines, set())
    note = "// Generated by derivations/x.gp."
    assert owner[2] == ("P", note)
    assert owner[4] == ("W", note)
    assert owner[6] == ("Z", "")


def test_a_year_cites_only_after_a_name_or_a_bracket() -> None:
    for cited in (
        "Knocke (1988)",
        "Vallado 2013",
        "(2010)",
        "Pavlis (2004)",
        "IERS TN 36",
    ):
        assert tool.CITE.search(cited), cited
    for plain in (
        "n = 2000 sectors",
        "at 1990 km",
        "confirmed (2026-10-28)",
        "a state (SI)",
    ):
        assert not tool.CITE.search(plain), plain


def test_a_named_path_may_give_its_extensions_in_braces() -> None:
    assert tool.exists("derivations/gauss_legendre_tables")
    assert tool.exists("tools/check-constants.py")
    assert not tool.exists("derivations/no_such_derivation")


if __name__ == "__main__":
    for name, test in sorted(globals().items()):
        if name.startswith("test_"):
            test()
            print("ok", name)
