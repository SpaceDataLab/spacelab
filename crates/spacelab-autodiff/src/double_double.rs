    #[test]
    fn the_sine_reduction_leaves_a_small_argument_alone() {
        // For `|a| < pi` the multiplier `n = floor(a/2pi + 0.5)` is zero and the reduced argument is
        // `a` itself, bit for bit. `SIN_REF` starts at 0.001 and nothing below it is tested, so a
        // reduction that went to the multiple *below* the nearest instead would quantise `a` onto
        // the double-double grid at 6.28 — half-step 4.9e-32, hence 4.9e-32/|a| relative — and
        // nothing would notice: 4.9e-27 at 1e-5, and everything at 1e-300.
        for a in [1e-10_f64, 1e-20, 1e-300] {
            let s = DoubleDouble::from(a).sin();
            assert_eq!(s.hi.to_bits(), a.to_bits(), "sin({a:e}) high word {}", s.hi);
        }
        // One argument where the cube does reach the high word, against the Maclaurin series summed
        // in double-double — an independent recomputation, not a copied constant. The a^7/5040 tail
        // is 2e-38, below the 2.5e-37 the double-double can represent at this magnitude.
        let a = DoubleDouble::from(1e-5);
        let a3 = a * a * a;
        let series = a - a3 / DoubleDouble::from(6.0) + a3 * a * a / DoubleDouble::from(120.0);
        let rel = ((a.sin() - series) / series).value().abs();
        assert!(rel < 1e-31, "sin(1e-5) against its own series: rel {rel:e}");
    }

    #[test]
    fn the_accurate_sum_carries_the_rounding_error_of_the_low_words() {
        // `dd_add` threads `e2`, the rounding error of `self.lo + rhs.lo`, and that term is the
        // whole difference between it and the cheap variant. `From<f64>` sets `lo = 0`, so `e2`
        // vanishes identically for any pair built that way — every fixture that adds two `f64`-born
        // values is blind to it by construction.
        //
        // The operands here are the correctly-rounded double-doubles of 1/3 and 2/3, so both low
        // words are non-zero. Their exact sum, taken as rationals over the four words, is
        // `1 - 3.0814879110195774e-33`, and that value is itself representable as a pair: the
        // accurate sum is not merely close here, it is exact. Reflecting `e2` moves the residual to
        // `+3.08e-33` — the answer crosses to the wrong side of one, 6.2e-33 relative, which is
        // half an ulp of the 106-bit format and precisely the precision `e2` exists to deliver.
        let third = DoubleDouble::new(0.333_333_333_333_333_3, 1.850_371_707_708_594e-17);
        let two_thirds = DoubleDouble::new(0.666_666_666_666_666_6, 3.700_743_415_417_188e-17);
        let sum = third + two_thirds;
        assert_eq!(sum.hi, 1.0);
        assert_eq!(sum.lo, -3.081_487_911_019_577_4e-33);
        assert!(sum < DoubleDouble::from(1.0));
    }

    #[test]
    fn the_long_division_keeps_its_third_quotient_correction() {
        // `dd_div` recovers the quotient one `f64` at a time and `q3` is the last of the three,
        // worth about an ulp of the low word. Negating it does not merely drop the correction, it
        // applies it backwards, so the error comes out roughly three times the uncorrected one.
        //
        // Operands are again the correctly-rounded double-doubles, of 1/10 and 1/3. Their exact
        // quotient over the four words rounds to `(0.3, 1.1102230246251566e-17)`; the long division
        // reaches that to 2.1e-33 relative, the mutated one lands 1.8e-32 away — nine times worse
        // and outside what the format can represent, yet invisible to any assertion pitched at
        // `f64` precision.
        let tenth = DoubleDouble::new(0.1, -5.551_115_123_125_783e-18);
        let third = DoubleDouble::new(0.333_333_333_333_333_3, 1.850_371_707_708_594e-17);
        let q = tenth / third;
        assert_eq!(q.hi, 0.3);
        assert_eq!(q.lo, 1.110_223_024_625_156_6e-17);
    }
