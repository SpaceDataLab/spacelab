#!/usr/bin/env python
"""Machine-extract the Modified Harris-Priester density table to Rust.

The table is the min/max density vs. altitude table of the Modified Harris-Priester model,
tabulated for mean solar activity over 100-1000 km. Its source of record is Montenbruck & Gill,
"Satellite Orbits" (Springer 2005), Table 3.8; the machine-readable canonical transcription used
here is Orekit's `HarrisPriester.java` (`org.orekit.models.earth.atmosphere.HarrisPriester`, the
`ALT_RHO` static), which cites that same book. Orekit stores altitude in metres and both densities
in kg/m3; those exact double literals are the values the Orekit oracle interpolates, so they are
emitted verbatim (only lowercasing the exponent `E`) — a diff against the Java is byte-trivial and
nothing is rounded. Never hand-transcribe these; regenerate with this script.

    uv run --no-project python derivations/harris_priester_tables.py <path-to-HarrisPriester.java> <out.rs>
"""

from __future__ import annotations

import re
import sys

_BLOCK = re.compile(r"ALT_RHO\s*=\s*\{(.*?)\}\s*;", re.DOTALL)
_ROW = re.compile(r"\{([^{}]*)\}")
_NUM = re.compile(r"[-+]?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][-+]?\d+)?")


def _fort_to_rust(tok: str) -> str:
    """Source real literal -> valid Rust f64 literal, digits preserved verbatim."""
    return tok.replace("E", "e").lstrip("+")


def main() -> None:
    src, out = sys.argv[1], sys.argv[2]
    with open(src) as fh:
        text = fh.read()
    m = _BLOCK.search(text)
    if not m:
        raise SystemExit("ALT_RHO block not found")
    rows = _ROW.findall(m.group(1))
    parsed: list[list[str]] = []
    for row in rows:
        toks = [_fort_to_rust(t) for t in _NUM.findall(row)]
        if len(toks) != 3:
            raise SystemExit(f"row has {len(toks)} values, expected 3: {row!r}")
        parsed.append(toks)
    n = len(parsed)
    lines = "\n".join(f"    [{', '.join(r)}]," for r in parsed)
    header = (
        "//! Modified Harris-Priester min/max density vs. altitude table — machine-generated by\n"
        "//! `derivations/harris_priester_tables.py` from Orekit's `HarrisPriester.java` (`ALT_RHO`),\n"
        "//! the canonical transcription of Montenbruck & Gill, \"Satellite Orbits\" (Springer 2005),\n"
        "//! Table 3.8, tabulated for mean solar activity over 100–1000 km. Do not edit by hand;\n"
        "//! regenerate from the source. Columns: `[altitude_m, rho_min_kg_m3, rho_max_kg_m3]`;\n"
        "//! values are verbatim Orekit double literals (the exact doubles its interpolation uses).\n"
    )
    body = (
        f"#[rustfmt::skip]\npub static ALT_RHO: [[f64; 3]; {n}] = [\n{lines}\n];\n"
    )
    with open(out, "w") as fh:
        fh.write(header + "\n" + body)
    print(f"wrote ALT_RHO [[f64; 3]; {n}] to {out}")


if __name__ == "__main__":
    main()
