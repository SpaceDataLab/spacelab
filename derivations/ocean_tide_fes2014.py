#!/usr/bin/env python
"""Machine-extract the FES2014b ocean-tide geopotential coefficients to a Rust table.

Sibling of `ocean_tide_fes2004.py`, same file format (`Doodson Darw l m DelC+ DelS+ DelC- DelS-`,
4 header lines, coefficients in units of 10^-11) and same emitted `OceanTideWave` shape -- but the
FES2014b file carries the *full* model to degree/order 100, so this generator applies **no degree
cap**: every row with degree n >= 2 is kept, exactly as the file gives it.

Two things differ from the FES2004 generator, both because FES2014b is high-degree and sparse:

  * No `MAX_DEGREE`/`MAX_ORDER` truncation. The project rule is never to cut model resolution for
    convenience; the caller picks the runtime evaluation degree on `OceanTide`, not the table.
  * No dense-triangle gap assertion. FES2004 (degree 6) is a full triangle, so a missing (n, m) there
    is a real defect; FES2014b at high degree is legitimately sparse, and `OceanTide::delta_cs` treats
    an absent (n, m) as zero (it only accumulates the rows that are present). So gaps are emitted as
    absence, never as a poisoned NaN.

The coefficients are emitted verbatim (primary-source precision); the 10^-11 unit is [`SCALE`],
applied at use exactly as Orekit's `FESCnmSnmReader` does. Waves are grouped by Doodson number and
sorted ascending, cells within a wave sorted by (n, m) -- a deterministic, diff-stable order.

Two files are written: the `.rs` module, and a sibling `.in` holding the coefficient body, which the
module pulls in with `include!`. The split is not cosmetic -- see the module header for the
measurement.

Source file: FES2014b.v1.Cnm-Snm (Om1+Om2 equilibrium, C20 without S1 wave), POT format, from
  https://api.sedoo.fr/formater-catalogue-prod/grace/direct/fes2014b.v1.Cnm-Snm_Om1+Om2C20_without_S1_wave.POT_format.txt

    uv run --no-project python derivations/ocean_tide_fes2014.py \
        ~/spacelab-data/fes2014b_Cnm-Snm.txt \
        crates/spacelab-propagation/src/ocean_tide_fes2014.rs
"""

from __future__ import annotations

import sys
from pathlib import Path

SCALE_LITERAL = "1.0e-11"
HEADER_LINES = 4
START_DEGREE = 2  # OceanTidesWave.START_DEGREE: n = 0, 1 do not perturb a spacecraft.
EXPECT_WAVES = 35
EXPECT_MAX_DEGREE = 100


def parse(path: str) -> tuple[
    dict[int, dict[tuple[int, int], tuple[str, str, str, str]]],
    dict[int, str],
    int,
]:
    """Group the file into {doodson: {(n, m): (cPlus, sPlus, cMinus, sMinus) verbatim tokens}}.

    Returns (waves, darwin-names, count-of-n>=2-rows-seen) -- the row count is an independent tally
    of the data lines used, checked against the emitted total as a self-check that nothing is dropped.
    """
    waves: dict[int, dict[tuple[int, int], tuple[str, str, str, str]]] = {}
    darwin: dict[int, str] = {}
    rows_seen = 0
    with open(path) as fh:
        for lineno, line in enumerate(fh):
            if lineno < HEADER_LINES:
                continue
            toks = line.split()
            if len(toks) < 8:
                continue
            try:
                doodson = int(toks[0].replace(".", "").replace(",", ""))
                n = int(toks[2])
                m = int(toks[3])
                coeffs = (toks[4], toks[5], toks[6], toks[7])
                for tok in coeffs:  # validate every token is a real number
                    float(tok)
            except ValueError:
                continue
            if n < START_DEGREE:  # NO upper cap -- keep every degree the file carries.
                continue
            waves.setdefault(doodson, {})[(n, m)] = coeffs
            darwin[doodson] = toks[1]
            rows_seen += 1
    return waves, darwin, rows_seen


def cells(wave: dict[tuple[int, int], tuple[str, str, str, str]]) -> list[tuple[int, int]]:
    """The (n, m) present in this wave (n >= 2), sorted -- sparse, no gap check (absent == 0)."""
    return sorted(wave)


def emit(waves, darwin, table_name: str) -> tuple[str, str, int]:
    blocks = []
    total = 0
    max_degree = 0
    for doodson in sorted(waves):
        rows = cells(waves[doodson])
        total += len(rows)
        max_degree = max(max_degree, max(n for (n, _m) in rows))
        lines = "\n".join(
            f"        ({n}, {m}, {waves[doodson][(n, m)][0]}, {waves[doodson][(n, m)][1]}, "
            f"{waves[doodson][(n, m)][2]}, {waves[doodson][(n, m)][3]}),"
            for (n, m) in rows
        )
        blocks.append(
            f"    // {darwin[doodson]} (Doodson {doodson})\n"
            f"    OceanTideWave {{ doodson: {doodson}, coeffs: &[\n{lines}\n    ] }},"
        )
    body = "\n".join(blocks)
    module = (
        "//! FES2014b ocean-tide geopotential coefficients (IERS Conventions 2010, Eq. 6.15) --\n"
        "//! machine-generated by `derivations/ocean_tide_fes2014.py` from `fes2014b_Cnm-Snm.txt`.\n"
        "//! Full model to degree/order 100 (no truncation); verbatim file values, the 10^-11 unit is\n"
        "//! [`SCALE`], applied at use. The runtime evaluation degree is chosen on\n"
        "//! [`crate::ocean_tide::OceanTide`], not here. Regenerate, never hand-edit.\n"
        "//!\n"
        f"//! The coefficient body lives in the sibling `{table_name}` and is included verbatim. Every\n"
        "//! source-level tool parses each `.rs` module in the tree whole -- `syn`, and through it\n"
        "//! `cargo-mutants`, plus `rustfmt` and `rust-analyzer` -- and this one table is large enough\n"
        "//! that it alone took `cargo mutants --list` on this crate from 9.6 s to over twelve minutes\n"
        "//! without finishing. `include!` hands rustc exactly the same tokens and leaves the module a\n"
        "//! page long, so the crate can be mutation-tested at all.\n\n"
        "// Verbatim FES2014b coefficients: many share the same few significant digits; the model name\n"
        "// FES2014b reads as camel-case to `doc_markdown`.\n"
        "#![allow(\n"
        "    clippy::unreadable_literal,\n"
        "    clippy::excessive_precision,\n"
        "    clippy::approx_constant,\n"
        "    clippy::doc_markdown\n"
        ")]\n\n"
        "use crate::ocean_tide_fes2004::OceanTideWave;\n\n"
        "/// FES2014b coefficient scale: file values are in units of 10^-11 (as FES2004; Orekit\n"
        "/// `FESCnmSnmReader`).\n"
        f"pub const SCALE: f64 = {SCALE_LITERAL};\n\n"
        f'include!("{table_name}");\n'
    )
    table = (
        f"// FES2014b coefficient body for `ocean_tide_fes2014.rs`, which `include!`s this file --\n"
        "// machine-generated by `derivations/ocean_tide_fes2014.py`. Regenerate, never hand-edit.\n\n"
        f"/// The {len(waves)} FES2014b waves to degree/order {max_degree} (no truncation), sorted by\n"
        "/// Doodson number; cells within a wave sorted by (n, m). Absent (n, m) contribute nothing.\n"
        f"pub static FES2014B_WAVES: &[OceanTideWave] = &[\n{body}\n];\n"
    )
    return module, table, total


def main() -> None:
    src, out = sys.argv[1], sys.argv[2]
    out_path = Path(out)
    table_path = out_path.with_name(f"{out_path.stem}_table.in")
    waves, darwin, rows_seen = parse(src)
    module, table, total = emit(waves, darwin, table_path.name)
    max_degree = max(n for w in waves.values() for (n, _m) in w)
    # Self-checks against the file, every run: shape, coverage, and no silent drops.
    assert len(waves) == EXPECT_WAVES, f"expected {EXPECT_WAVES} waves, got {len(waves)}"
    assert max_degree == EXPECT_MAX_DEGREE, f"expected max degree {EXPECT_MAX_DEGREE}, got {max_degree}"
    assert total == rows_seen, f"emitted {total} rows but file had {rows_seen} (n>=2) -- data dropped"
    out_path.write_text(module)
    table_path.write_text(table)
    print(
        f"{len(waves)} waves, max degree {max_degree}, {total} (n>=2) coefficient rows "
        f"-> {out_path} + {table_path}"
    )


if __name__ == "__main__":
    main()
