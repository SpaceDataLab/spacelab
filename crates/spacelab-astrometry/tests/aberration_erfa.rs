/// Well conditioned near zero, unlike `acos(u.v)`, which loses half the mantissa and reports 0.003"
/// of shift for a direction that is exactly along the velocity and cannot shift at all.
fn separation(u: Vec3, v: Vec3) -> f64 {
    u.cross(v).norm().atan2(u.dot(v))
}

