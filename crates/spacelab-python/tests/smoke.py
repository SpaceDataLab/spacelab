def test_gauss_newton_fits_a_state_via_python_callback():
    truth = [1.0, -2.0, 3.0, 0.5, -0.5, 4.0]

    def model(
        x,
    ):  # direct observation of each component: residual = computed - observed = x_i - truth_i, ∂/∂x = e_i
        rows = []
        for i in range(6):
            h = [0.0] * 6
            h[i] = 1.0
            rows.append((h, x[i] - truth[i], 1.0))
        return rows

    x, cov, converged, _iters, _cost = sl.gauss_newton(model, [0.0] * 6)
    assert converged, "Gauss-Newton did not converge"
    for i in range(6):
        close(x[i], truth[i], 1e-6)
        # unit-weight direct observations: information matrix is I, so the covariance is I
        close(cov[i][i], 1.0, 1e-9)


