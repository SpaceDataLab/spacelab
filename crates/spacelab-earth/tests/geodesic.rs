fn point(lat: f64, lon: f64) -> SurfacePoint {
    SurfacePoint {
        latitude: Angle::from_radians(lat),
        longitude: Angle::from_radians(lon),
    }
}

fn inverse(lat1: f64, lon1: f64, lat2: f64, lon2: f64) -> GeodesicInverse {
    geodesic_inverse(point(lat1, lon1), point(lat2, lon2)).unwrap()
}

/// An angle difference reduced to (−π, π].
fn angle_diff(a: f64, b: f64) -> f64 {
    let d = (a - b) % core::f64::consts::TAU;
    if d > PI {
        d - core::f64::consts::TAU
    } else if d <= -PI {
        d + core::f64::consts::TAU
    } else {
        d
    }
}

/// The distance between two nearby surface points, metres, to first order.
fn separation(lat_a: f64, lon_a: f64, lat_b: f64, lon_b: f64) -> f64 {
    let north = EQUATORIAL_RADIUS * (lat_a - lat_b);
    let east = EQUATORIAL_RADIUS * lat_b.cos() * angle_diff(lon_a, lon_b);
    north.hypot(east)
}

/// A reproducible uniform stream on [0, 1) (Knuth's MMIX generator), for the round trips.
struct Lcg(u64);

impl Lcg {
    // The top 53 bits, so the conversion is exact.
    #[allow(clippy::cast_precision_loss)]
    fn next(&mut self) -> f64 {
        self.0 = self
            .0
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        (self.0 >> 11) as f64 / (1u64 << 53) as f64
    }

    /// A latitude uniform on the sphere.
    fn latitude(&mut self) -> f64 {
        (2.0 * self.next() - 1.0).asin()
    }

    fn longitude(&mut self) -> f64 {
        PI * (2.0 * self.next() - 1.0)
    }
}

/// `a E(e)`, the quarter meridian: `ellipsoid_geodesic.gp` prints it from PARI's `ellE` and again
/// by quadrature of the meridian arc, equal to 25 digits.
const QUARTER_MERIDIAN: f64 = 10_001_965.729_312_722_811_739_62;

/// The tolerance on a distance: two ulps of a 2·10⁷ m line.
const TOL_DISTANCE: f64 = 7.5e-9;

/// The tolerance on a computed end point, which carries the round-off of a whole direct solution:
/// the bound Karney states for his double-precision implementation on WGS 84 (2013, §7).
const TOL_POSITION: f64 = 15e-9;

/// (G2) The inverse problem against the defining integrals solved at 50 digits: the distance, and
/// each azimuth through the sideways displacement `m12 δα` it causes.
#[test]
fn the_inverse_solves_the_defining_integrals_at_50_digits() {
    let (mut worst_s, mut worst_side) = (0.0f64, 0.0f64);
    for (i, r) in INVERSE.iter().enumerate() {
        let g = inverse(r[0], r[1], r[2], r[3]);
        let ds = (g.distance.metres() - r[4]).abs();
        let side = r[7].abs()
            * angle_diff(g.azimuth1.radians(), r[5])
                .abs()
                .max(angle_diff(g.azimuth2.radians(), r[6]).abs());
        assert!(ds <= TOL_DISTANCE, "row {i}: distance off by {ds:e} m");
        assert!(
            side <= TOL_DISTANCE,
            "row {i}: azimuths move the far end {side:e} m"
        );
        worst_s = worst_s.max(ds);
        worst_side = worst_side.max(side);
    }
    println!(
        "inverse vs 50 digits, {} rows: worst distance {:.3} nm, worst m12·δα {:.3} nm",
        INVERSE.len(),
        worst_s * 1e9,
        worst_side * 1e9
    );
}

/// (G2) The direct problem against the defining integrals solved at 50 digits: the end point and
/// the azimuth there, including lines longer than a meridian circle and negative distances.
#[test]
fn the_direct_solves_the_defining_integrals_at_50_digits() {
    let (mut worst_p, mut worst_a) = (0.0f64, 0.0f64);
    for (i, r) in DIRECT.iter().enumerate() {
        let d = geodesic_direct(
            point(r[0], r[1]),
            Angle::from_radians(r[2]),
            Length::from_metres(r[3]),
        )
        .unwrap();
        let dp = separation(
            d.point.latitude.radians(),
            d.point.longitude.radians(),
            r[4],
            r[5],
        );
        let da = angle_diff(d.azimuth.radians(), r[6]).abs();
        assert!(dp <= TOL_POSITION, "row {i}: end point off by {dp:e} m");
        assert!(da <= 1e-14, "row {i}: azimuth off by {da:e} rad");
        worst_p = worst_p.max(dp);
        worst_a = worst_a.max(da);
    }
    println!(
        "direct vs 50 digits, {} rows: worst end point {:.3} nm, worst azimuth {worst_a:.2e} rad",
        DIRECT.len(),
        worst_p * 1e9
    );
}

/// (G3) Along the equator up to its conjugate point, `λ12 ≤ (1 − f)π`, the geodesic is the equator
/// itself: `s12 = a λ12`, heading due east.
#[test]
fn the_equator_is_the_geodesic_up_to_its_conjugate_point() {
    for lam in [1e-9, 0.5, 1.0, 2.0, 3.0, 3.13] {
        let g = inverse(0.0, 0.0, 0.0, lam);
        let expected = EQUATORIAL_RADIUS * lam;
        assert!((g.distance.metres() - expected).abs() <= 2.0 * f64::EPSILON * expected);
        assert_eq!(g.azimuth1.radians(), FRAC_PI_2);
        assert_eq!(g.azimuth2.radians(), FRAC_PI_2);
        let west = inverse(0.0, 0.0, 0.0, -lam);
        assert_eq!(west.distance, g.distance);
        assert_eq!(west.azimuth1.radians(), -FRAC_PI_2);
    }
}

/// (G3) The meridian arc from the equator to the pole is `a E(e)`, between the poles twice that
/// whatever the longitudes, and two antipodal points on the equator are joined over a pole.
#[test]
fn meridian_arcs_are_the_complete_elliptic_integral() {
    let north = inverse(0.0, 0.3, FRAC_PI_2, 0.3);
    assert!((north.distance.metres() - QUARTER_MERIDIAN).abs() <= TOL_DISTANCE);
    assert_eq!(
        (north.azimuth1.radians(), north.azimuth2.radians()),
        (0.0, 0.0)
    );
    let south = inverse(0.0, 0.3, -FRAC_PI_2, 0.3);
    assert_eq!(south.distance, north.distance);
    assert_eq!(south.azimuth1.radians(), PI);
    for lon2 in [0.0, 1.0, 2.5, PI] {
        let g = inverse(-FRAC_PI_2, 0.0, FRAC_PI_2, lon2);
        assert!((g.distance.metres() - 2.0 * QUARTER_MERIDIAN).abs() <= TOL_DISTANCE);
    }
    // λ12 is π less half an ulp of π here, so the line passes within a nanometre of a pole.
    let antipodal = inverse(0.0, 0.0, 0.0, PI);
    assert!((antipodal.distance.metres() - 2.0 * QUARTER_MERIDIAN).abs() <= TOL_DISTANCE);
}

/// (G3) Coincident points are zero apart with both azimuths 0 — including the poles, where any two
/// longitudes name the same point.
#[test]
fn coincident_points_are_zero_apart() {
    for (lat, lon) in [
        (0.0, 0.0),
        (0.9, -1.0),
        (-1.2, 3.0),
        (FRAC_PI_2, 0.4),
        (-FRAC_PI_2, -2.0),
    ] {
        let g = inverse(lat, lon, lat, lon);
        assert_eq!(g.distance.metres(), 0.0);
        assert_eq!((g.azimuth1.radians(), g.azimuth2.radians()), (0.0, 0.0));
    }
    for (lon1, lon2) in [(0.0, 1.0), (-2.0, 3.0)] {
        let g = inverse(FRAC_PI_2, lon1, FRAC_PI_2, lon2);
        assert!(g.distance.metres() <= 1e-9, "{:e}", g.distance.metres());
    }
}

/// (G5) Karney's worked examples (2013, Tables 2, 3 and 4–6), inputs in degrees as printed and
/// outputs to the digits printed.
#[test]
fn karneys_printed_examples() {
    let deg = |x: f64| x.to_radians();
    // Table 2, the direct problem.
    let d = geodesic_direct(
        point(deg(40.0), 0.0),
        Angle::from_degrees(30.0),
        Length::from_metres(10_000_000.0),
    )
    .unwrap();
    assert!((d.point.latitude.degrees() - 41.793_310_205_06).abs() < 5e-12);
    assert!((d.point.longitude.degrees() - 137.844_900_043_77).abs() < 5e-12);
    assert!((d.azimuth.degrees() - 149.090_169_318_07).abs() < 5e-12);
    // Tables 4-6, nearly antipodal: the astroid start, then Newton.
    let g = inverse(deg(-30.0), 0.0, deg(29.9), deg(179.8));
    assert!((g.distance.metres() - 19_989_832.827_610).abs() < 5e-7);
    assert!((g.azimuth1.degrees() - 161.890_524_736_33).abs() < 5e-12);
    assert!((g.azimuth2.degrees() - 18.090_737_245_74).abs() < 5e-12);
    // Table 3, a short line.
    let g = inverse(deg(-30.123_45), 0.0, deg(-30.123_44), deg(0.000_05));
    assert!((g.distance.metres() - 4.944_208).abs() < 5e-7);
    // Rounding the inputs to doubles moves each end by up to 0.35 nm per coordinate, which turns
    // the azimuths of a 5 m line by up to 3e-10 rad: they are held through s12 δα.
    let side = |printed: f64, got: Angle| {
        g.distance.metres() * (got.radians() - printed.to_radians()).abs()
    };
    assert!(side(77.043_533_542_37, g.azimuth1) < 1.5e-9);
    assert!(side(77.043_508_449_13, g.azimuth2) < 1.5e-9);
}

/// (G4) Direct and inverse undo each other: the inverse's azimuth and distance, through the direct
/// problem, land on the second point; and a direct line shorter than half a meridian is the
/// shortest, so the inverse recovers its length and azimuth.
#[test]
fn direct_and_inverse_undo_each_other() {
    let mut rng = Lcg(20_261_125);
    let (mut worst_land, mut worst_s, mut worst_side) = (0.0f64, 0.0f64, 0.0f64);
    for _ in 0..2000 {
        let (lat1, lon1, lat2, lon2) = (
            rng.latitude(),
            rng.longitude(),
            rng.latitude(),
            rng.longitude(),
        );
        let g = inverse(lat1, lon1, lat2, lon2);
        let d = geodesic_direct(point(lat1, lon1), g.azimuth1, g.distance).unwrap();
        let land = separation(
            d.point.latitude.radians(),
            d.point.longitude.radians(),
            lat2,
            lon2,
        );
        assert!(
            land <= TOL_POSITION,
            "({lat1}, {lon1}) -> ({lat2}, {lon2}): lands {land:e} m off"
        );
        assert!(angle_diff(d.azimuth.radians(), g.azimuth2.radians()).abs() <= 1e-13);
        worst_land = worst_land.max(land);

        let (azi, s12) = (PI * (2.0 * rng.next() - 1.0), 1e7 * rng.next());
        let e = geodesic_direct(
            point(lat1, lon1),
            Angle::from_radians(azi),
            Length::from_metres(s12),
        )
        .unwrap();
        let back = geodesic_inverse(point(lat1, lon1), e.point).unwrap();
        let ds = (back.distance.metres() - s12).abs();
        // Each azimuth error moves the far end sideways by at most s12 per radian.
        let side = s12 * angle_diff(back.azimuth1.radians(), azi).abs();
        assert!(
            ds <= TOL_DISTANCE && side <= TOL_DISTANCE,
            "azimuth {azi}, {s12} m: {ds:e}, {side:e}"
        );
        worst_s = worst_s.max(ds);
        worst_side = worst_side.max(side);
    }
    println!(
        "round trips, 2000 each: inverse then direct lands {:.3} nm off; direct then inverse: \
         distance {:.3} nm, s12·δα {:.3} nm",
        worst_land * 1e9,
        worst_s * 1e9,
        worst_side * 1e9
    );
}

/// (G4) Swapping the ends reverses the geodesic, and reflecting both points in the equator or in a
/// meridian reflects it: the same distance, the azimuths mapped accordingly.
#[test]
fn the_symmetries_of_the_ellipsoid_hold() {
    let mut rng = Lcg(7);
    for _ in 0..500 {
        let (lat1, lon1, lat2, lon2) = (
            rng.latitude(),
            rng.longitude(),
            rng.latitude(),
            rng.longitude(),
        );
        let g = inverse(lat1, lon1, lat2, lon2);
        let swapped = inverse(lat2, lon2, lat1, lon1);
        let reflected = inverse(-lat1, lon1, -lat2, lon2);
        let mirrored = inverse(lat1, -lon1, lat2, -lon2);
        for (h, a1, a2) in [
            (
                swapped,
                g.azimuth2.radians() + PI,
                g.azimuth1.radians() + PI,
            ),
            (
                reflected,
                PI - g.azimuth1.radians(),
                PI - g.azimuth2.radians(),
            ),
            (mirrored, -g.azimuth1.radians(), -g.azimuth2.radians()),
        ] {
            assert!((h.distance.metres() - g.distance.metres()).abs() <= TOL_DISTANCE);
            assert!(angle_diff(h.azimuth1.radians(), a1).abs() <= 1e-12);
            assert!(angle_diff(h.azimuth2.radians(), a2).abs() <= 1e-12);
        }
    }
}

