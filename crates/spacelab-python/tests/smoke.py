def test_luni_solar_perturbs_a_geo_orbit():
    mu = 3.986004418e14
    r_geo = 42_164e3
    r0 = [r_geo, 0.0, 0.0]
    v0 = [0.0, (mu / r_geo) ** 0.5, 0.0]
    span = 43_200.0  # half a day

    ls = sl.propagate_luni_solar_dense(r0, v0, span, 4, 0.0, tol=1e-10)
    geo = sl.propagate_geopotential_dense(r0, v0, span, 4, tol=1e-10)
    rl, _ = ls.eval(span)
    rg, _ = geo.eval(span)
    # Sun+Moon steadily displace a GEO orbit; over half a day it is well over a hundred metres.
    assert norm([rl[i] - rg[i] for i in range(3)]) > 100.0, norm(
        [rl[i] - rg[i] for i in range(3)]
    )
    assert 4.1e7 < norm(rl) < 4.3e7, norm(rl)  # still near GEO radius

    # Enabling a typical GEO-comsat SRP (~1e-7 m/s²) perturbs the trajectory further.
    srp = sl.propagate_luni_solar_dense(
        r0, v0, span, 4, 0.0, srp_reference_acceleration=1e-7, tol=1e-10
    )
    rs, _ = srp.eval(span)
    assert norm([rs[i] - rl[i] for i in range(3)]) > 1.0, "SRP had no effect"


