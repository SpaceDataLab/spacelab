def test_itrf_frame_interpolation_matches_exact_within_a_micron():
    # The fast ITRF propagators interpolate the slow CIP (precession-nutation) geometry from a grid
    # and apply the exact ERA per stage. `propagate_j2_itrf_dense` (interpolated) vs
    # `propagate_j2_itrf_eop_dense` (exact per-stage frame) on the SAME orbit and epochs, with the EOP
    # zeroed and tt == ut1 == utc, isolates the CIP-interpolation error as the final-state gap.
    day_ns = 86_400 * 10**9
    e = 8766 * day_ns  # ~2024, ns since J2000
    mu, j2, re = 3.986004418e14, 1.08262668e-3, 6_378_137.0
    r0 = [6.9e6, 1.2e6, 2.0e6]
    v0 = [-1500.0, 6000.0, 3500.0]
    span = (
        6 * 3600.0
    )  # 6 hours; ERA sweeps 90°, so the fast path is genuinely exercised
    tol = 1e-11
    fast = sl.propagate_j2_itrf_dense(r0, v0, span, mu, j2, re, e, e, tol=tol)
    zero = [0.0, 0.0]
    exact = sl.propagate_j2_itrf_eop_dense(
        r0,
        v0,
        span,
        mu,
        j2,
        re,
        e,
        0.0,
        [0.0, span],
        zero,
        zero,
        zero,
        zero,
        zero,
        tol=tol,
    )
    rf = fast.eval(span)[0]
    rx = exact.eval(span)[0]
    gap = norm([rf[i] - rx[i] for i in range(3)])
    assert gap < 1e-6, f"CIP-interpolation trajectory gap {gap:.3e} m exceeds 1 µm"
    print(f"  (frame-interpolation gap over 6 h: {gap:.2e} m)")


def test_j2_double_double_below_the_f64_floor():
    mu, re, j2 = 3.986004418e14, 6_378_137.0, 1.082626e-3
    r0 = 7_000e3
    vc = (mu / r0) ** 0.5
    period = 2 * math.pi * (r0**3 / mu) ** 0.5
    n, revs = 1024, 10
    dt, steps = period / n, n * revs
    start, vel = [r0, 0.0, 0.0], [0.0, vc, 0.0]
    rf, _ = sl.propagate_j2_precision(
        start, vel, mu, j2, re, dt, steps, precision="f64"
    )
    rd, _ = sl.propagate_j2_precision(start, vel, mu, j2, re, dt, steps, precision="dd")
    # dd is the round-off-free reference; the gap is the f64 round-off dd removes on a perturbed orbit.
    roundoff = norm([rf[i] - rd[i] for i in range(3)])
    assert roundoff > 1e-9, roundoff


