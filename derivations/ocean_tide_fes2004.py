#!/usr/bin/env python
"""Machine-extract the FES2004 ocean-tide geopotential coefficients to a Rust table.

Each Doodson tide wave carries, per spherical-harmonic degree n and order m, the prograde (C+, S+)
and retrograde (C-, S-) coefficients of IERS Conventions 2010 Eq. 6.15. The file lists them in units
of 10^-11 (the scale Orekit's `FESCnmSnmReader` applies, `LazyLoadedGravityFields` line 178:
`new FESCnmSnmReader(FES_CNM_SNM_FILENAME, 1.0e-11)` -- the stale "10^-12" in the reader javadoc is a
doc bug; the file header and the constructor both say 10^-11).

Waves are grouped by Doodson number (the first column with its dot removed: "255.555" -> 255555) and
sorted ascending, so the Rust accumulation order matches the Orekit bench (which sorts identically) --
removing floating-point summation order as a source of disagreement. Coefficients are emitted verbatim
from the file (primary-source precision); the 10^-11 scale is applied at use, exactly as Orekit does
(`scale * parseDouble(token)`), keeping the port bit-for-bit faithful to the oracle.

Only degree n >= 2 affects a spacecraft (`OceanTidesWave.START_DEGREE = 2`); the file's n = 0, 1 rows
are dropped. Truncated to degree = order = 6 to match the Orekit gate. The generator asserts the used
triangle (n = 2..deg, m = 0..min(n,ord)) has no gaps -- a gap would be NaN in Orekit and poison the
wave.

    uv run --no-project python derivations/ocean_tide_fes2004.py \
        /tmp/orekit-bench/orekit-data-main/fes2004_Cnm-Snm.dat \
        crates/spacelab-propagation/src/ocean_tide_fes2004.rs
"""

from __future__ import annotations

import sys

MAX_DEGREE = 6
MAX_ORDER = 6
SCALE_LITERAL = "1.0e-11"
HEADER_LINES = 4


def parse(path: str) -> dict[int, dict[tuple[int, int], tuple[str, str, str, str]]]:
    """Group the file into {doodson: {(n, m): (cPlus, sPlus, cMinus, sMinus) verbatim tokens}}."""
    waves: dict[int, dict[tuple[int, int], tuple[str, str, str, str]]] = {}
    darwin: dict[int, str] = {}
    with open(path) as fh:
        for lineno, line in enumerate(fh):
            if lineno < HEADER_LINES:
                continue
            toks = line.split()
            if len(toks) < 8:
                continue
            try:
                doodson = int(toks[0].replace(".", "").replace(",", ""))
                n = int(toks[2])
                m = int(toks[3])
                coeffs = (toks[4], toks[5], toks[6], toks[7])
                for tok in coeffs:  # validate every token is a real number
                    float(tok)
            except ValueError:
                continue
            if n > MAX_DEGREE or m > MAX_ORDER:
                continue
            waves.setdefault(doodson, {})[(n, m)] = coeffs
            darwin[doodson] = toks[1]
    return waves, darwin


def used_cells(cells: dict[tuple[int, int], tuple[str, str, str, str]]) -> list[tuple[int, int]]:
    """The (n, m) Orekit iterates in addContribution: n = 2..deg, m = 0..min(n, ord)."""
    deg = max(n for (n, _m) in cells)
    ordr = max(m for (_n, m) in cells)
    out = []
    for n in range(2, deg + 1):
        for m in range(min(n, ordr) + 1):
            if (n, m) not in cells:
                raise ValueError(f"gap at (n={n}, m={m}) -- NaN in Orekit, wave poisoned")
            out.append((n, m))
    return out


def emit(waves, darwin) -> str:
    blocks = []
    total = 0
    for doodson in sorted(waves):
        cells = waves[doodson]
        rows = used_cells(cells)
        total += len(rows)
        lines = "\n".join(
            f"        ({n}, {m}, {cells[(n, m)][0]}, {cells[(n, m)][1]}, "
            f"{cells[(n, m)][2]}, {cells[(n, m)][3]}),"
            for (n, m) in rows
        )
        blocks.append(
            f"    // {darwin[doodson]} (Doodson {doodson})\n"
            f"    OceanTideWave {{ doodson: {doodson}, coeffs: &[\n{lines}\n    ] }},"
        )
    body = "\n".join(blocks)
    return (
        "//! FES2004 ocean-tide geopotential coefficients (IERS Conventions 2010, Eq. 6.15) --\n"
        "//! machine-generated by `derivations/ocean_tide_fes2004.py` from `fes2004_Cnm-Snm.dat`.\n"
        "//! Verbatim file values; the 10^-11 unit is [`SCALE`], applied at use (as Orekit does).\n"
        "//! Regenerate, never hand-edit.\n\n"
        "// Verbatim FES2004 coefficients: many share the same few significant digits.\n"
        "#![allow(\n"
        "    clippy::unreadable_literal,\n"
        "    clippy::excessive_precision,\n"
        "    clippy::approx_constant\n"
        ")]\n\n"
        "/// FES2004 coefficient scale: file values are in units of 10^-11 (Orekit `FESCnmSnmReader`).\n"
        f"pub const SCALE: f64 = {SCALE_LITERAL};\n\n"
        "/// One Doodson tide wave: its Doodson number and the fully-normalized prograde/retrograde\n"
        "/// coefficients `(n, m, C+, S+, C-, S-)` (verbatim, in units of [`SCALE`]) for degree n >= 2.\n"
        "pub struct OceanTideWave {\n"
        "    /// Doodson number, e.g. 255555 for M2 (the six-digit tidal argument code).\n"
        "    pub doodson: u32,\n"
        "    /// `(degree n, order m, C+, S+, C-, S-)` rows; absent (n, m) contribute nothing.\n"
        "    pub coeffs: &'static [(u8, u8, f64, f64, f64, f64)],\n"
        "}\n\n"
        f"/// The {len(waves)} FES2004 waves, truncated to degree = order = {MAX_DEGREE}, sorted by\n"
        "/// Doodson number (matching the Orekit oracle's accumulation order).\n"
        "#[rustfmt::skip]\n"
        f"pub static FES2004_WAVES: &[OceanTideWave] = &[\n{body}\n];\n"
    )


def main() -> None:
    src, out = sys.argv[1], sys.argv[2]
    waves, darwin = parse(src)
    with open(out, "w") as fh:
        fh.write(emit(waves, darwin))
    total = sum(len(used_cells(cells)) for cells in waves.values())
    print(f"{len(waves)} waves, {total} (n>=2) coefficient rows -> {out}")


if __name__ == "__main__":
    main()
