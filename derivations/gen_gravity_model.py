#!/usr/bin/env -S uv run --quiet python
"""Generate the embedded spherical-harmonic gravity-model table for the tesseral geopotential.

Streams a model from ICGEM (GFZ Potsdam), truncates to a chosen degree, verifies its own constants
against the known field (J2 from C20), and emits a Rust const table of *fully-normalized* coefficients
that `GeoPotential::from_normalized` de-normalizes. Model-agnostic: pick any ICGEM model by name.

Default model is XGM2019e (Zingerle, Pail, Gruber, Oikonomidou 2020) — the newest freely-available
combined model. At degree <= 20 the field is pinned by GRACE/GOCE and is identical across modern models
(EGM2008 / EIGEN-6C4 / XGM2019e) to ~11 significant figures; the model choice only matters at the high
degrees the (unnormalized) recursion cannot yet reach. NGA's EGM2020 is not publicly released.

Provenance: values are DATA read from the authoritative ICGEM `.gfc`, emitted as Python `repr()`
decimals — the shortest string that round-trips to the same f64 under IEEE round-to-nearest (which
Rust's parser also uses) — so the committed literal is the nearest f64 to the source value.

Run:  timeout 120 uv run --no-project python derivations/gen_gravity_model.py [MODEL] [degree]
"""

from __future__ import annotations

import math
import pathlib
import sys
import urllib.request

# ICGEM model .gfc URLs (hash-addressed, from icgem.gfz-potsdam.de/tom_longtime).
MODELS = {
    "XGM2019e": "https://icgem.gfz-potsdam.de/getmodel/gfc/8e01a2aba4f291ac0638b79a390155713b70fdc9b266981023c756839c11c9b8/XGM2019e.gfc",
    "EIGEN-6C4": "https://icgem.gfz-potsdam.de/getmodel/gfc/7fd8fe44aa1518cd79ca84300aef4b41ddb2364aef9e82b7cdaabdb60a9053f1/EIGEN-6C4.gfc",
    "GOCO06s": "https://icgem.gfz-potsdam.de/getmodel/gfc/32ec2884630a02670476f752d2a2bf1c395d8c8d6d768090ed95b4f04b0d5863/GOCO06s.gfc",
    "EGM2008": "https://icgem.gfz-potsdam.de/getmodel/gfc/c50128797a9cb62e936337c890e4425f03f0461d7329b09a8cc8561504465340/EGM2008.gfc",
}
OUT = pathlib.Path(__file__).parent.parent / "crates/spacelab-propagation/src/geopotential_coeffs.rs"


def fnum(tok: str) -> float:
    return float(tok.replace("d", "e").replace("D", "e"))


def main() -> int:
    model = sys.argv[1] if len(sys.argv) > 1 else "XGM2019e"
    degree = int(sys.argv[2]) if len(sys.argv) > 2 else 20
    if model not in MODELS:
        print(f"unknown model {model!r}; known: {', '.join(MODELS)}")
        return 2

    gm = re = norm = tide = None
    coeffs: list[tuple[int, int, float, float]] = []
    print(f"fetching {model} from ICGEM, truncating to degree {degree} …")
    with urllib.request.urlopen(MODELS[model], timeout=90) as resp:
        in_body = False
        for raw in resp:
            line = raw.decode("latin-1").strip()
            if not in_body:
                if line.startswith("earth_gravity_constant"):
                    gm = fnum(line.split()[1])
                elif line.startswith("radius"):
                    re = fnum(line.split()[1])
                elif line.startswith("norm"):
                    norm = line.split()[1]
                elif line.startswith("tide_system"):
                    tide = line.split()[1]
                elif line.startswith("end_of_head"):
                    in_body = True
                continue
            if not line.startswith("gfc"):
                continue
            _, n_s, m_s, c_s, s_s = line.split()[:5]
            n, m = int(n_s), int(m_s)
            if n > degree:
                break
            if n >= 2:  # C00 = 1 is set by the constructor; C10 = C11 = 0 (mass-centred)
                coeffs.append((n, m, fnum(c_s), fnum(s_s)))

    assert norm == "fully_normalized", f"unexpected normalization {norm}"
    assert gm and re, "missing GM/radius in header"
    c20 = next(c for (n, m, c, _s) in coeffs if n == 2 and m == 0)
    j2 = -math.sqrt(5.0) * c20
    print(f"  GM = {gm:.6e}  Re = {re:.4f}  tide = {tide}  norm = {norm}")
    print(f"  C20 = {c20:.12e}  ->  J2 = {j2:.9e}  (expect ~1.0826e-3)")
    assert abs(j2 - 1.0826e-3) < 1e-6, f"J2 sanity failed: {j2}"
    print(f"  parsed {len(coeffs)} coefficients (degrees 2..{degree})")

    lines = [
        "//! Embedded spherical-harmonic gravity-model coefficients (fully normalized), truncated.",
        "//!",
        f"//! GENERATED by `derivations/gen_gravity_model.py` from the ICGEM `{model}.gfc` model",
        f"//! (tide system: {tide}, fully normalized). Do not edit by hand. `MODEL_GM`/`MODEL_RE` are the",
        "//! model's own defining constants; the coefficients are referenced to them, so use these, not",
        "//! WGS-84, when evaluating the field.",
        "",
        "#![allow(clippy::unreadable_literal, clippy::doc_markdown)] // generated numeric data",
        "",
        '/// Name of the embedded gravity model.',
        f'pub const MODEL_NAME: &str = "{model}";',
        "/// Model gravitational parameter, m³/s².",
        f"pub const MODEL_GM: f64 = {gm!r};",
        "/// Model reference (equatorial) radius, m.",
        f"pub const MODEL_RE: f64 = {re!r};",
        "/// Highest degree/order in [`MODEL_COEFFS`].",
        f"pub const MODEL_MAX_DEGREE: usize = {degree};",
        "",
        "/// Fully-normalized `(n, m, C̄_nm, S̄_nm)` for degrees 2..=MODEL_MAX_DEGREE.",
        "#[rustfmt::skip]",
        "pub const MODEL_COEFFS: &[(usize, usize, f64, f64)] = &[",
    ]
    lines += [f"    ({n}, {m}, {c!r}, {s!r})," for (n, m, c, s) in coeffs]
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"  wrote {OUT.relative_to(OUT.parents[3])}  (model = {model})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
