    fn agree_to(label: &str, got: [f64; 3], want: [f64; 3], bar: f64) {
        for i in 0..3 {
            let miss = (got[i] - want[i]).abs() / want[i].abs();
            assert!(miss < bar, "{label}, axis {i}: {miss:.3e} relative");
        }
    }

    /// Both grid loops stop on a strict `<`, and a `<=` would add one more element — a whole extra
    /// crown at the horizon, or a duplicate of the first azimuthal sector. Neither boundary is
    /// approached by any fixture, so both ties have to be constructed.
    ///
    /// The horizon `acos(Rₑ/|r|)` lands exactly on the fifth crown offset at this radius, so one
    /// ulp of altitude either side of it must not change the crown count; a `<=` puts a crown
    /// between them. Under Lambert's cosine that crown weighs nothing: every element centred on the
    /// horizon emits at 90° to its normal, so this half now shows the horizon is where the weight
    /// vanishes and can no longer tell `<` from `<=`. The azimuth wraps exactly onto `2π` at
    /// `Δ = 2π/28.5` — where `<=` sweeps the zero sector twice — while one ulp more of `Δ` leaves
    /// the sector count where it was.
    #[test]
    fn the_grid_loops_stop_before_their_bounds_not_on_them() {
        let on_the_crown = [
            3_740_734.896_746_353_7,
            2_244_440.938_047_812_3,
            6_077_974.792_545_862_5,
        ];
        let below = on_the_crown.map(|c: f64| f64::from_bits(c.to_bits() - 1));
        // The fifth crown offset, accumulated the way the loop accumulates it — 1.5Δ then four
        // additions, which is not the same double as 5.5Δ.
        let mut fifth_crown = 1.5 * ARES;
        for _ in 0..4 {
            fifth_crown += ARES;
        }
        assert_eq!(
            libm::acos(AE / libm::sqrt(dot3(&on_the_crown, &on_the_crown))),
            fifth_crown,
            "the horizon no longer falls on a crown boundary; re-derive the radius"
        );
        agree_to(
            "horizon on a crown boundary",
            flux_at(ARES, on_the_crown),
            flux_at(ARES, below),
            1e-12,
        );

        let wrapping = f64::from_bits(0x3fcc_381e_af74_f83f); // 2π/28.5, to the bit
        let sat = [6.9e6, 1.1e6, 2.3e6];
        agree_to(
            "azimuth wrapping onto 2π",
            flux_at(wrapping, sat),
            flux_at(f64::from_bits(wrapping.to_bits() + 1), sat),
            1e-12,
        );
    }

    /// The force monomorphises under [`spacelab_autodiff::Dual`] (the STM path is real) and its AD
    /// Jacobian `∂a/∂r` matches central finite differences — the same AD every other force uses. A
    /// coarse grid keeps the dual evaluation cheap.
    #[test]
    fn ad_jacobian_matches_finite_differences() {
        use spacelab_autodiff::Dual;

        let sun = [1.1e11, -0.9e11, -0.4e11];
        let make = |ares: f64| KnockeEarthRadiation {
            model: model(),
            sun: FixedBody(sun),
            equatorial_radius: AE,
            angular_resolution: step(ares),
            reference_epoch_offset: 1.33e9,
            attitude: |_t: f64| IDENTITY,
        };
        let coarse = make(0.3);
        let sat = [6.9e6, 1.1e6, 2.3e6];

        let rd = [
            Dual::<3>::variable(sat[0], 0),
            Dual::<3>::variable(sat[1], 1),
            Dual::<3>::variable(sat[2], 2),
        ];
        let a = coarse.acceleration(
            Dual::<3>::constant(0.0),
            &rd,
            &[Dual::<3>::constant(0.0); 3],
        );
        let a_f64 = coarse.acceleration(0.0, &sat, &[0.0; 3]);
        // A few ulps, not bit equality: `Dual` divides as `u·(1/v)`, one rounding more than f64's
        // `u/v`, so the two instantiations can part by an ulp per quotient (1.7e-16 measured here).
        for i in 0..3 {
            assert!(
                (a[i].value() - a_f64[i]).abs() < 4.0 * f64::EPSILON * a_f64[i].abs(),
                "value drift on axis {i}: {:e} relative",
                (a[i].value() - a_f64[i]) / a_f64[i]
            );
        }

        let h = 1.0; // 1 m about ~7300 km — the active-element set is stable across it
        for j in 0..3 {
            let mut rp = sat;
            let mut rm = sat;
            rp[j] += h;
            rm[j] -= h;
            let ap = coarse.acceleration(0.0, &rp, &[0.0; 3]);
            let am = coarse.acceleration(0.0, &rm, &[0.0; 3]);
            for i in 0..3 {
                let fd = (ap[i] - am[i]) / (2.0 * h);
                let ad = a[i].grad()[j];
                assert!(
                    (fd - ad).abs() <= 1e-5 * ad.abs() + 1e-20,
                    "∂a[{i}]/∂r[{j}]: AD {ad:.6e} vs FD {fd:.6e}"
                );
            }
        }
    }
