    /// `exp` reduces by `R = a − m·ln2` with `m = floor(a/ln2 + 0.5)` — round to *nearest*, so that
    /// `|R| ≤ ½ ln 2`. The residue the reduction leaves is `ln 2`'s own double-double truncation
    /// times `m`, which makes `m = 0` the one regime where the reduction costs nothing at all and
    /// only the series error remains. [`EXP_REF`] never samples it: its smallest non-zero argument
    /// is `1e-10`, where `exp` is `1 + a` to well inside a double-double, and every other entry has
    /// `|m| ≥ 1`. So the arguments below are the interior of the first bin, `|a| < ½ ln 2`, on
    /// exactly-representable binary fractions. Rounding the *other* way — `floor(a/ln2 − 0.5)` —
    /// shifts `m` by one everywhere, and the factor of two it costs `2ᵐ` and `exp(R)` cancels, so
    /// the answer stays right to 31 digits and [`EXP_REF`]'s 1e-30 bar cannot see it; what it
    /// cannot do is leave `m` at zero. Measured worst relative error over the four arguments below:
