def test_an_apparent_elevation_mask_is_the_geometric_one_the_atmosphere_makes_of_it():
    """`Sensor.elevation` takes the geometric mask; a station's spec is the apparent one.

    Until this existed a Python caller could not correct the difference at all -- the bridge exposed
    no refraction. It is worth 0.81-20.3 s of pass edge with the same sign on every edge of every
    pass, so it is a bias rather than noise.
    """
    apparent = 10.0
    geometric = sl.refraction_geometric(apparent)
    # The atmosphere lifts the satellite, so the geometric mask that reproduces an apparent one has
    # to sit lower -- by Bennett's 5.3 arcminutes at 10 degrees.
    assert geometric < apparent
    close((apparent - geometric) * 60.0, 5.3, 2e-2)

    # The two published fits are not each other's inverse; the round trip closes to the few
    # arcseconds by which they disagree, and asserting tighter would assert they are.
    back = sl.refraction_apparent(geometric)
    assert abs(back - apparent) * 3600.0 < 6.0

    # Refraction grows toward the horizon and the mask constructor agrees with the conversion.
    assert sl.refraction_geometric(0.0) < sl.refraction_geometric(45.0) - 45.0 + 1e-12
    assert sl.Sensor.elevation_apparent(apparent) is not None

    # Domains: below the horizon there is no ray to unbend, and the mask says so as an exception
    # rather than as a silently wrong threshold.
    assert sl.refraction_geometric(-0.1) is None
    assert sl.refraction_apparent(-2.0) is None
    try:
        sl.Sensor.elevation_apparent(-0.1)
    except ValueError:
        pass
    else:
        raise AssertionError("an apparent mask below the horizon must be refused")

    # And the corrected mask actually moves the windows, in the direction refraction moves them:
    # a lower geometric threshold opens the pass earlier and closes it later.
    cells = sl.grid_cells([0.0], [0.0])
    a = 6_378_137.0 + 550e3
    args = (a, math.radians(53.0), 0.0, 0.0)
    plain = sl.coverage_metrics(
        *args, sl.Sensor.elevation(apparent), cells, 43_200.0, tol=2.0
    )
    bent = sl.coverage_metrics(
        *args, sl.Sensor.elevation_apparent(apparent), cells, 43_200.0, tol=2.0
    )
    assert bent[0][1] > plain[0][1], "the refracted mask did not lengthen the coverage"


def test_diurnal_aberration_matches_erfa_at_a_real_station():
    """The station's own rotation, not the Earth's orbit around the Sun.

    Station and satellite share the 29.8 km/s barycentric velocity that makes the 20.5" constant of
    aberration, and a shared velocity cancels in a geocentric frame. What does not cancel is the
    465.1 m/s the station is carried at by the Earth's rotation. The fixture below is ERFA `ab` --
    the SOFA lineage, which shares no code with this library -- at a 34.9 degree station looking at
    its own zenith in ITRF, generated by `tools/gen_aberration_oracle.py`.
    """
    station = [-2377784.4496136275, -4666664.740638489, 3629288.6474473714]
    spin = [0.0, 0.0, 7.292115146706979e-05]
    erfa = [1.135113833978216e-06, -5.783693864850948e-07, 0.9999999999991885]

    velocity = sl.diurnal_velocity(station, spin)
    close(math.hypot(*velocity), 381.926, 1e-3)
    # omega x r is horizontal: a station is carried east, never up.
    close(sum(v * s for v, s in zip(velocity, station, strict=True)), 0.0, 1e-6)

    seen = sl.aberration_apply(velocity, [0.0, 0.0, 1.0])
    # atan2 of the cross and dot products, not acos: at 1e-6 rad `acos` reports sqrt(2*eps) and
    # loses half the mantissa, which is enough to hide a wrong answer at this size.
    cross = [
        seen[1] * erfa[2] - seen[2] * erfa[1],
        seen[2] * erfa[0] - seen[0] * erfa[2],
        seen[0] * erfa[1] - seen[1] * erfa[0],
    ]
    dot = sum(a * b for a, b in zip(seen, erfa, strict=True))
    assert math.atan2(math.hypot(*cross), dot) < 1e-15, "the bridge disagrees with ERFA"

    # The published size of the effect, and the exact inverse.
    shift = math.atan2(math.hypot(seen[0], seen[1]), seen[2]) * 180.0 * 3600.0 / math.pi
    close(shift, 0.262775, 1e-6)
    back = sl.aberration_remove(velocity, seen)
    assert max(abs(b - z) for b, z in zip(back, [0.0, 0.0, 1.0], strict=True)) < 1e-15

    # A velocity at the speed of light is not an observer, and a point is not a direction.
    assert sl.aberration_apply([0.0, 3.0e8, 0.0], [1.0, 0.0, 0.0]) is None
    assert sl.aberration_remove(velocity, [0.0, 0.0, 0.0]) is None


