//! Knocke Earth-reradiated radiation pressure — albedo (reflected sunlight) and thermal-IR emission —
//! a port of Orekit's `KnockeRediffusedForceModel` (Knocke, Ries & Tapley, "Earth Radiation Pressure
//! Effects on Satellites", 1988), with Lambert's cosine where Orekit has another (below).
//!
//! # Why
//!
//! [`crate::forces::SolarRadiationPressure`] and [`crate::spacecraft::PanelSrp`] model the *direct*
//! Sun→satellite flux. But the satellite also sees the Earth: the visible cap reradiates sunlight it
//! reflects (**albedo**) and the thermal infrared it emits (**IR**). For a LEO satellite this Earth
//! flux is of order `10⁻⁸ … 10⁻⁷ m/s²` — a Tier-1 accuracy term Orekit carries and a bare direct-SRP
//! model omits.
//!
//! # The model (Orekit `KnockeRediffusedForceModel`)
//!
//! The Earth is a sphere of radius `Rₑ`, divided into elementary areas over an **angular grid**. Each
//! area reradiates according to Lambert's law; the flux the satellite receives is the sum of the
//! elementary fluxes. The same spacecraft [`RadiationModel`] that turns the Sun's flux into an
//! acceleration turns this rediffused flux into one — so the absorption/specular/diffuse optics are
//! reused verbatim, only the flux source changes.
//!
//! * **Zonal albedo / emissivity.** With `φ` the geocentric latitude of an element,
//!   `a(φ,t) = A0 + A1(t)·P1(sinφ) + A2·P2(sinφ)` and `e(φ,t) = E0 + E1(t)·P1 + E2·P2`, where `P1`,
//!   `P2` are Legendre polynomials and the first-order coefficients carry an **annual** term
//!   `A1(t) = C0 + C1·cos(ωΔt) + C2·sin(ωΔt)` (likewise `E1`), `ω = 2π / Julian year`, `Δt` measured
//!   from Knocke's reference epoch 1981-12-22T00:00:00 UTC. Coefficients are Orekit's
//!   ([`A0`]…[`E2`]).
//! * **Solar flux at Earth.** `Φ = ES_COEFF · c / d²`, `d` the Earth–Sun distance in AU (JPL-SSD AU).
//! * **Elementary flux.** An element of area `dA` at position `p` (on the sphere) contributes only if
//!   the satellite is above its horizon, `cosα = p̂·(r − p)/|r − p| > 0`. Its outgoing irradiance is
//!   `a·Φ·cosθ☉ + e·Φ/4` (albedo weighted by the solar incidence `cosθ☉ ≥ 0`, IR unconditional),
//!   attenuated by the Lambert/inverse-square factor `dA·cosα / (π·|r−p|³)` and divided by `c`, along
//!   the element→satellite direction `r − p`.
//!
//!   Orekit 13.1.7 takes `cosα = p̂·r̂`, the geocentric angle, instead. That is not Lambert's law: on
//!   a uniform sphere it gives 1.97× the view factor `(R/r)²` at 500 km, and twice the exitance at
//!   the surface. `derivations/knocke_lambert.mac` integrates both cosines in closed form, and
//!   `a_polar_night_cap_matches_its_closed_form` holds the grid to each. The Orekit cosine is kept
//!   for tests only, so the grid can still be compared with Orekit's element for element.
//! * **Grid.** A central spherical cap of half-angle `Δ` (the angular resolution) about the
//!   sub-satellite point, then concentric crowns at colatitudes `1.5Δ, 2.5Δ, …` out to the visible
//!   horizon `acos(Rₑ/|r|)`, each crown swept in azimuth by steps of `Δ`. Ring/sector centres are
//!   generated by [Hipparchus-convention rotations](rotate_vector) of the sub-satellite point, and the
//!   loop bounds and areas are ported exactly so the quadrature sum matches Orekit element-for-element.
//!
//! # Automatic differentiation
//!
//! Written once over any [`Scalar`], so the Jacobian — and the STM — comes from AD like every other
//! force. The satellite position `r` carries the derivatives; the Sun position, the seasonal
//! coefficients (functions of time only) and the grid angles are `f64` constants. The **discrete**
//! choices — how many crowns fit under the horizon, whether an element is visible/sunlit — are taken
//! from the `f64` value (Orekit's field path does the same, reading `getNorm().getReal()`): the
//! element count is a step function of position and the STM is not defined across a step, exactly as
//! the [`crate::forces::SolarRadiationPressure`] shadow gate.

// The Knocke zonal model names its coefficients A0/A2/C0-2, E0/E2/K0-2 (the source's names) and the
// geometry speaks in single letters (r, p, φ, α, θ). These are the domain's names, not terse locals.
#![allow(clippy::many_single_char_names, clippy::similar_names)]

