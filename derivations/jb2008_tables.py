#!/usr/bin/env python
"""Machine-extract the JB2008 coefficient tables from the canonical FORTRAN to Rust.

The constants are the model's official values as published in Bruce R. Bowman's reference
`JB2008.for` (Space Environment Technologies; the source of record for the Jacchia-Bowman 2008
model). They are emitted verbatim -- the exact decimal digits of the FORTRAN `DATA` statements,
only rewriting the `D` exponent marker as `e` and normalising `0.` -> `0.0` so the literal is
valid Rust -- so a diff against the FORTRAN is byte-trivial and nothing is rounded. Never
hand-transcribe these; regenerate with this script.

Program units are parsed separately because the local array name `C` is reused for two different
tables (7 mean-molecular-mass coefficients in FUNCTION XAMBAR, 23 dTc coefficients in SUBROUTINE
DTSUB). The mathematical constants pi, 2*pi and ln(10) are intentionally NOT taken from the
FORTRAN (which truncates them, e.g. AL10 = 2.3025851); the Rust port uses full-precision values
from `core::f64::consts`, matching Orekit and the SatelliteToolbox Julia port.

    uv run --no-project python derivations/jb2008_tables.py <path-to-JB2008.for> <out.rs>
"""

from __future__ import annotations

import re
import sys

# (fortran_unit, fortran_name) -> (rust_name, declared_len)
_WANTED: dict[tuple[str, str], tuple[str, int]] = {
    ("JB2008", "ALPHA"): ("ALPHA", 5),
    ("JB2008", "AMW"): ("AMW", 6),
    ("JB2008", "FRAC"): ("FRAC", 4),
    ("JB2008", "WT"): ("WT", 5),
    ("JB2008", "CHT"): ("CHT", 4),
    ("XAMBAR", "C"): ("CXAMB", 7),
    ("DTSUB", "B"): ("BDT", 19),
    ("DTSUB", "C"): ("CDT", 23),
    ("SEMIAN08", "FZM"): ("FZM", 5),
    ("SEMIAN08", "GTM"): ("GTM", 10),
}

_UNIT = re.compile(r"\b(?:SUBROUTINE|FUNCTION)\s+(\w+)", re.IGNORECASE)
_DATA = re.compile(
    r"^\s*DATA\s+(\w+)\s*(?:\(\s*(\d+)\s*\))?\s*/(.*)/\s*$", re.IGNORECASE
)
_NUM = re.compile(r"[-+]?(?:\d+\.\d*|\.\d+|\d+)(?:[dDeE][-+]?\d+)?")


def _logical_lines(text: str):
    """Yield (unit_name, statement) for a fixed-form FORTRAN source.

    Comment lines (C/c/*/! in column 1) are dropped; continuation lines (non-blank,
    non-zero column 6) are folded onto the statement they continue. The active program
    unit name is tracked so identically-named DATA arrays in different units stay distinct.
    """
    unit = "?"
    current: str | None = None
    for raw in text.splitlines():
        if not raw.strip():
            continue
        if raw[0] in "Cc*!":  # column-1 comment
            continue
        col6 = raw[5] if len(raw) > 5 else " "
        body = raw[6:72]  # statement field, columns 7..72
        if col6 not in (" ", "0") and current is not None:  # continuation
            current += " " + body.strip()
            continue
        if current is not None:
            yield unit, current
        current = body.strip()
        m = _UNIT.search(raw)
        if m:
            unit = m.group(1).upper()
    if current is not None:
        yield unit, current


def _fort_to_rust(tok: str) -> str:
    """FORTRAN real literal -> valid Rust f64 literal, digits preserved verbatim."""
    s = tok.replace("D", "e").replace("d", "e").replace("E", "e")
    s = s.lstrip("+")  # Rust rejects a leading '+' sign on a literal
    s = re.sub(r"(?<![\d])\.", "0.", s)  # leading '.5' -> '0.5'
    s = re.sub(r"\.(?=e|$)", ".0", s)  # trailing '0.' / '0.e0' -> '0.0' / '0.0e0'
    return s


def main() -> None:
    src, out = sys.argv[1], sys.argv[2]
    with open(src) as fh:
        text = fh.read()

    # (unit, name) -> either list[str] (whole-array) or dict[int, str] (per-element).
    collected: dict[tuple[str, str], object] = {}
    for unit, stmt in _logical_lines(text):
        m = _DATA.match(stmt)
        if not m:
            continue
        name, idx, vals = m.group(1).upper(), m.group(2), m.group(3)
        key = (unit, name)
        if key not in _WANTED:
            continue
        toks = [_fort_to_rust(t) for t in _NUM.findall(vals)]
        if idx is None:
            collected[key] = toks
        else:
            collected.setdefault(key, {})
            collected[key][int(idx)] = toks[0]  # type: ignore[index]

    blocks = [
        "//! JB2008 (Jacchia-Bowman 2008) coefficient tables -- machine-generated by\n"
        "//! `derivations/jb2008_tables.py` from the canonical FORTRAN `JB2008.for`\n"
        "//! (Bruce R. Bowman, Space Environment Technologies; the model's source of record).\n"
        "//! Do not edit by hand; regenerate from the source. Values are verbatim FORTRAN digits\n"
        "//! (`D` exponent rewritten as `e`). The mathematical constants pi/2pi/ln(10) live in the\n"
        "//! algorithm module at full precision, not here.\n"
    ]
    emitted = []
    for (unit, name), (rust_name, n) in _WANTED.items():
        raw = collected.get((unit, name))
        if raw is None:
            raise SystemExit(f"missing DATA for {unit}:{name}")
        if isinstance(raw, dict):
            vals = [raw.get(i + 1, "0.0") for i in range(n)]
        else:
            vals = list(raw)
        assert len(vals) == n, f"{unit}:{name} got {len(vals)} values, expected {n}"
        body = ", ".join(vals)
        blocks.append(f"#[rustfmt::skip]\npub static {rust_name}: [f64; {n}] = [{body}];\n")
        emitted.append((rust_name, n))

    with open(out, "w") as fh:
        fh.write("\n".join(blocks))
    for rust_name, n in emitted:
        print(f"  {rust_name:6s} [f64; {n}]")
    print(f"wrote {len(emitted)} tables to {out}")


if __name__ == "__main__":
    main()
