def test_switchable_precision_double_double_beats_f64():
    mu = 3.986004418e14
    r0 = 7_000e3
    vc = (mu / r0) ** 0.5
    period = 2 * math.pi * (r0**3 / mu) ** 0.5
    n, revs = 1024, 15
    dt = period / n
    steps = n * revs
    start = [r0, 0.0, 0.0]
    rf, _ = sl.propagate_two_body(start, [0.0, vc, 0.0], mu, dt, steps, precision="f64")
    rd, _ = sl.propagate_two_body(start, [0.0, vc, 0.0], mu, dt, steps, precision="dd")
    err_f = norm([rf[i] - start[i] for i in range(3)])
    err_d = norm([rd[i] - start[i] for i in range(3)])
    assert err_d * 5 < err_f, (
        err_f,
        err_d,
    )  # dd removes the f64 integration round-off floor


