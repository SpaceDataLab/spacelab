    /// The seasonal phase reads `ω·(reference_epoch_offset + t)`, and every Orekit fixture calls at
    /// `t = 0`, where `offset + 0` and `offset − 0` are the same number and nothing distinguishes
    /// the two. Shifting the reference epoch and advancing the evaluation time must be the same
    /// thing, and a quarter of a year apart the season must actually have moved.
    #[test]
    fn only_the_sum_of_the_epoch_offset_and_the_elapsed_time_reaches_the_season() {
        let sat = [6.9e6, 1.1e6, 2.3e6];
        let quarter = 0.25 * JULIAN_YEAR;
        let split = at(1.33e9, quarter, sat);
        let summed = at(1.33e9 + quarter, 0.0, sat);
        for i in 0..3 {
            let miss = (split[i] - summed[i]).abs() / summed[i].abs();
            assert!(
                miss < 1e-14,
                "axis {i}: the split and summed epochs differ by {miss:.3e}"
            );
        }
        let unmoved = at(1.33e9, 0.0, sat);
        assert!(
            (0..3).any(|i| (split[i] - unmoved[i]).abs() > 1e-6 * unmoved[i].abs()),
            "a quarter year did not move the seasonal coefficients at all"
        );
    }

    /// Two of Knocke's four seasonal coefficients are `0.0` in the published table (`C2`, `K2`), so
    /// `+ C2·sin φ` contributes nothing whichever operator joins it — with one exception: at
