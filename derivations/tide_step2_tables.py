#!/usr/bin/env python
"""Machine-extract the IERS 2010 Table 6.5a/b/c solid-tide Step-2 constituents to Rust.

Each constituent contributes τ (the GMST multiplier, 1 diurnal / 0 long-period / 2 semidiurnal), the
five Delaunay multipliers (l, l', F, D, Ω), and the in-phase / out-of-phase amplitudes (already the
A·δk·H products, in 10⁻¹²). The argument is θ = τ·(GMST+π) − Σ(Delaunay·args); see solid_tide.rs.

Source: the IERS Conventions 2010 tables bundled in the Orekit jar
(assets/org/orekit/IERS-conventions/2010/tab6.5{a,b,c}.txt). Verbatim; regenerate, never hand-edit.

    uv run --no-project python derivations/tide_step2_tables.py <tab-dir> <out.rs>
"""

from __future__ import annotations

import sys


def parse(path: str, ip_from_end: int, op_from_end: int | None) -> list[tuple[int, list[int], float, float]]:
    rows = []
    with open(path) as fh:
        text = fh.read()
    for line in text.splitlines():
        toks = line.split()
        j = next((i for i, t in enumerate(toks) if "," in t and t.replace(",", "").isdigit()), None)
        if j is None:
            continue
        k = j + 1
        while k < len(toks):  # skip deg/hr float that may follow the Doodson number
            try:
                int(toks[k])
                break
            except ValueError:
                k += 1
        try:
            mult = [int(toks[k + i]) for i in range(11)]  # 6 Doodson + 5 Delaunay
            ip = float(toks[len(toks) - ip_from_end])
            op = 0.0 if op_from_end is None else float(toks[len(toks) - op_from_end])
        except (ValueError, IndexError):
            continue
        rows.append((mult[0], mult[6:11], ip, op))
    return rows


def emit(name: str, rows: list[tuple[int, list[int], float, float]]) -> str:
    lines = "\n".join(
        f"    ({tau}, [{d[0]}, {d[1]}, {d[2]}, {d[3]}, {d[4]}], {ip:.1f}, {op:.1f}),"
        for tau, d, ip, op in rows
    )
    return (
        f"/// `(τ, [l, l', F, D, Ω], amp_ip, amp_op)` per constituent (amplitudes in 10⁻¹²).\n"
        f"#[rustfmt::skip]\n"
        f"pub static {name}: [(i32, [i32; 5], f64, f64); {len(rows)}] = [\n{lines}\n];\n"
    )


def main() -> None:
    tabdir, out = sys.argv[1].rstrip("/"), sys.argv[2]
    di = parse(f"{tabdir}/tab6.5a.txt", 2, 1)
    lp = parse(f"{tabdir}/tab6.5b.txt", 3, 1)
    sd = parse(f"{tabdir}/tab6.5c.txt", 1, None)
    hdr = (
        "//! IERS 2010 solid-tide Step-2 (frequency-dependent) constituents — machine-generated by\n"
        "//! `derivations/tide_step2_tables.py` from IERS Conventions 2010 Tables 6.5a/b/c. Verbatim.\n"
    )
    with open(out, "w") as fh:
        fh.write("\n".join([hdr, emit("DIURNAL", di), emit("LONG_PERIOD", lp), emit("SEMIDIURNAL", sd)]))
    print(f"diurnal {len(di)}, long-period {len(lp)}, semidiurnal {len(sd)} -> {out}")


if __name__ == "__main__":
    main()
