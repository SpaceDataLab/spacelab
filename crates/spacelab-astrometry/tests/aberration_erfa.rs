//! Diurnal aberration against ERFA `ab` — the SOFA lineage, which shares no code with this crate.
//!
//! The Earth's 29.8 km/s orbital motion is the famous 20.5" constant of aberration and it does *not*
//! apply to a satellite observation: station and satellite share the Earth's barycentric velocity and
//! a shared velocity cancels in a geocentric frame. What is left is the station's own rotation --
//! 465.1 m/s at the equator, falling as `cos(phi)` -- worth **0.320"** at the equator and **0.262"**
//! at 34.9 degrees. That is a hundred times a plate's centroiding error and it turns with the hour
//! angle, so it does not average out either.
//!
//! `erfa.ab(pnat, v, s, bm1)` computes `pnat*bm1 + w1*v + w2*(v - pdv*pnat)` normalised, with
//! `w2 = SRS/s` the solar light-bending term rather than aberration. The fixture is generated at
//! `s = 1e12` au, which drives `w2` to about 2e-20 and leaves exactly the special-relativistic boost
//! `Aberration::apply` implements -- so this compares two implementations of one formula and the
//! residual should be round-off, not a modelling difference. Generated by `tools/gen_aberration_oracle.py`.

// `unreadable_literal` is allowed because the `CASES` block below is *generated*: every digit is
// ERFA's output, written by `tools/gen_aberration_oracle.py` at full `repr` precision. Grouping them
// would mean the generator emitting separators, which is one more transformation between the oracle
// and the fixture and therefore one more place a digit can go missing.
// `float_cmp` likewise: the assertion that a station on the rotation axis has *exactly* zero
// velocity is about an exact cancellation in a cross product, and a tolerance there would pass on a
// sign error whose residue happened to be small.
#![allow(
    clippy::float_cmp,
    clippy::unreadable_literal,
    clippy::unwrap_used,
    clippy::expect_used
)]

use spacelab_astrometry::reduce::{Aberration, SPEED_OF_LIGHT};
